/// The repository root: this crate's directory, two levels up. The
/// both-ways resolution is [`test_utils::source::crate_dir`]'s, shared.
fn repo_root() -> PathBuf {
    let root = test_utils::source::crate_dir(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("the repository root resolves");
    assert!(
        root.join("Cargo.toml").is_file(),
        "{} is not the repository root",
        root.display()
    );
    root
}

/// Is this bound spelled as the bracket door alone?
fn is_sole_bracket(bound: &str) -> bool {
    let b: String = bound.split_whitespace().collect();
    matches!(
        b.trim_end_matches(','),
        "Bounds" | "Enclosure" | "geom_core::Bounds" | "geom_core::Enclosure" | "crate::Bounds"
    )
}

/// The end of the `<…>` opened at `open`, by angle depth.
///
/// **A list this cannot close stops the census** rather than being
/// skipped: angle brackets are not reliably balanced in Rust (a `->` or a
/// comparison inside a bound breaks the count), and a site the walk
/// cannot read is a site it must not drop — `flagged_census.rs`'s
/// turbofish scan takes the same asymmetry for the same reason.
fn angle_end(code: &str, open: usize) -> usize {
    let mut depth = 0i32;
    for (i, ch) in code[open..].char_indices() {
        match ch {
            '<' => depth += 1,
            '>' => {
                depth -= 1;
                if depth == 0 {
                    return open + i;
                }
            }
            '{' | ';' => break,
            _ => {}
        }
    }
    panic!(
        "a generic parameter list at byte {open} does not close before its item's body: {:.120}",
        &code[open..]
    )
}

/// Split at top-level commas, ignoring commas nested in any bracket.
fn top_level_params(inner: &str) -> Vec<&str> {
    let (mut out, mut depth, mut start) = (Vec::new(), 0i32, 0usize);
    for (i, ch) in inner.char_indices() {
        match ch {
            '<' | '(' | '[' => depth += 1,
            '>' | ')' | ']' => depth -= 1,
            ',' if depth == 0 => {
                out.push(&inner[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    out.push(&inner[start..]);
    out
}

/// The `where` clause between an item's generic list and its body, if it
/// has one. Found by the KEYWORD rather than by `"where "`: `rustfmt` puts
/// a multi-line clause's first bound on the next line, which is how the
/// one where-clause site in the tree (`impl Bounds for Dual<T>`) is
/// written and how a search for the keyword-plus-space misses it.
fn where_clause(after_list: &str) -> Option<&str> {
    let head = after_list.split('{').next()?;
    let at = head.find("where")?;
    let before_ok = at == 0 || !is_ident(head.as_bytes()[at - 1]);
    let rest = &head[at + 5..];
    if !before_ok || !rest.starts_with(char::is_whitespace) {
        return None;
    }
    Some(rest)
}

/// The subject a site is keyed on: the function's name, or the impl
/// header with its generic list, whitespace-collapsed.
fn subject_of(code: &str, keyword: &str, kw_at: usize, list_end: usize) -> String {
    if keyword == "impl" {
        let head = &code[kw_at..list_end + 1];
        let head: String = head.split_whitespace().collect::<Vec<_>>().join(" ");
        // `impl<T: Bounds> Enclosure for T {` keys on the whole header;
        // the trailing type is what tells the two projection impls apart.
        let tail = code[list_end + 1..]
            .split('{')
            .next()
            .unwrap_or("")
            .split("where")
            .next()
            .unwrap_or("")
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ");
        return format!("{head} {tail}").trim().to_string();
    }
    code[kw_at + keyword.len()..]
        .trim_start()
        .split(|c: char| !(c.is_alphanumeric() || c == '_'))
        .next()
        .unwrap_or("")
        .to_string()
}

/// Every sole-bracket-bound site under `crates/*/src`, as
/// `(path, subject)`.
fn walk(root: &Path) -> BTreeSet<(String, String)> {
    let mut out = BTreeSet::new();
    let crates = root.join("crates");
    for entry in std::fs::read_dir(&crates).expect("crates dir listing") {
        let src = entry.expect("dir entry").path().join("src");
        if !src.is_dir() {
            continue;
        }
        for path in test_utils::source::rust_sources(&src) {
            let text = std::fs::read_to_string(&path).expect("readable source file");
            let code = test_utils::source::code_only(&text);
            let rel = path
                .strip_prefix(root)
                .expect("a walked file lies under the root")
                .to_string_lossy()
                .replace('\\', "/");
            for (kw_at, keyword) in item_keywords(&code) {
                let after = &code[kw_at + keyword.len()..];
                let Some(rel_open) = after.find(['<', '{', ';', '(']) else {
                    continue;
                };
                if !after[rel_open..].starts_with('<') {
                    continue;
                }
                let open = kw_at + keyword.len() + rel_open;
                let end = angle_end(&code, open);
                let mut hit = top_level_params(&code[open + 1..end])
                    .iter()
                    .filter_map(|p| p.split_once(':'))
                    .any(|(_, bound)| is_sole_bracket(bound));
                // The `where` clause of the same item, read the same way.
                if !hit && let Some(clause) = where_clause(&code[end..]) {
                    hit = top_level_params(clause)
                        .iter()
                        .filter_map(|p| p.split_once(':'))
                        .any(|(_, bound)| is_sole_bracket(bound));
                }
                if hit {
                    out.insert((rel.clone(), subject_of(&code, keyword, kw_at, end)));
                }
            }
        }
    }
    out
}

/// Every `fn` / `impl` / `struct` / `trait` / `enum` / `type` keyword in
/// the code view, as `(offset, keyword)`, with word boundaries checked so
/// `transform` does not contain a `fn`.
fn item_keywords(code: &str) -> Vec<(usize, &'static str)> {
    let mut out = Vec::new();
    for kw in ["fn", "impl", "struct", "trait", "enum", "type"] {
        let mut i = 0;
        while let Some(rel) = code[i..].find(kw) {
            let at = i + rel;
            i = at + kw.len();
            let before_ok = at == 0 || !is_ident(code.as_bytes()[at - 1]);
            let after_ok = code.as_bytes().get(i).is_none_or(|b| !is_ident(*b));
            if before_ok && after_ok {
                out.push((at, kw));
            }
        }
    }
    out.sort_unstable();
    out
}

fn is_ident(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_'
}

/// **The roster is the tree's set, not a subset of it.**
///
/// A door that arrives, moves, or is deleted reds this row until its line
/// is written or removed — which is the whole instrument: the rule that
/// prescribes the sole bound now has something that watches the class,
/// and it is not the gate (which cannot see this form by construction).
#[test]
fn every_sole_bracket_bound_door_is_in_the_roster() {
    let root = repo_root();
    let found = walk(&root);
    let listed: BTreeSet<(String, String)> = ROSTER
        .iter()
        .map(|s| (s.path.to_string(), s.subject.to_string()))
        .collect();
    let arrived: Vec<_> = found.difference(&listed).collect();
    let gone: Vec<_> = listed.difference(&found).collect();
    assert!(
        arrived.is_empty() && gone.is_empty(),
        "the sole-bracket-bound roster no longer matches the tree.\n  \
         arrived or moved (owe a roster line WITH its disposition): {arrived:#?}\n  \
         listed but no longer present (delete the line): {gone:#?}"
    );
}

/// A disposition is a claim, and an empty one is a line that looks
/// discharged and is not. (`reader_census.rs` carries this row for its
/// own ledger; the shape is deliberately the same.)
#[test]
fn every_roster_line_states_a_reason() {
    for site in ROSTER {
        let reason = match site.why {
            Payload(r) | Selection(r) | Impl(r) | HandedOff(r) => r,
        };
        assert!(
            reason.len() > 20,
            "{}::{} carries no real reason: {reason:?}",
            site.path,
            site.subject
        );
    }
}
