//! **The sole-`T: Bounds` roster, computed.**
//!
//! [`geom_core::Bounds`]'s scope rule prescribes the SOLE bound — a
//! parameter whose only bound is the bracket door — and that is exactly
//! the form no instrument watches: `scripts/gates/bounds-allowlist.sh`
//! plants a sole bracket bound as its must-not-fire case, because firing
//! on it would red every certification file in `geom` and `geom-brep`.
//! The rule the gate enforces is the COMPOUND one. This suite is the
//! other half: it walks every crate's `src/` and pins the sole-bound
//! roster with a disposition per door, so a new one cannot arrive
//! unnoticed the way the six in `topo` did.
//!
//! **Why a roster and not a threshold.** The population is large and
//! mostly legitimate, so a count would move for reasons nobody wants to
//! read about and an allowlist of files would say nothing about which
//! doors are in them. What a reader needs is the door and the reason it
//! is sound at a `Dual` — which is the disposition column, and which is
//! also the column a grep cannot compute. The set equality below is what
//! keeps the column honest: a door that arrives, moves crate, or is
//! deleted reds this suite until someone writes its line.
//!
//! # What the walk matches, and what it cannot
//!
//! It reads every `crates/*/src/**/*.rs` through
//! [`test_utils::source::code_only`], so a bound named in prose or inside
//! a string literal is not a hit, and a real site commented out stops
//! being one — the direction that matters. Inside that view it takes
//! every generic parameter list introduced by `fn` / `impl` / `struct` /
//! `trait` / `enum` / `type`, splits it at top-level commas (so a
//! multi-line list, and a list whose other parameters are lifetimes or
//! consts, are read the same as a one-line one), and keeps the parameters
//! whose WHOLE bound is `Bounds` or `Enclosure`, path-qualified or not.
//! `where` clauses are read the same way.
//!
//! **What it cannot match, stated rather than left to be discovered:**
//!
//! 1. **`impl Bounds` in argument position** — `fn f(x: impl Bounds)` is
//!    the same door with no generic parameter to read. None exists today.
//! 2. **A renamed import** (`use geom_core::Bounds as Bracket;`), which
//!    makes the bound spell a name this walk does not know. None exists
//!    today; the gate's KNOWN GAP 3/4 is the same hole one form over.
//! 3. **A bound reached by a supertrait obligation** — the gate's KNOWN
//!    GAP 2, and `S213`'s subject: `trait Lane: Bounds` puts the bracket
//!    door on every `T: Lane` without spelling it here.
//! 4. **A bound generated by a macro** whose text is assembled rather
//!    than written (`concat_idents!`, a bound pasted from a macro
//!    argument). A macro BODY written out in the file is matched — the
//!    `geom` projection impls below are inside one.
//!
//! Closing (2) and (3) for the tree needs a walk of every generic
//! parameter's RESOLVED bound set — a `rustc` driver or a
//! `rust-analyzer` query, not a bigger regex — which is the standing
//! answer this file does not replace.

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

/// Why a sole bracket bound is sound at this door — the column a grep
/// cannot compute, and the reason this file is a roster rather than a
/// count.
#[derive(Debug, Clone, Copy)]
enum Why {
    /// The bracket read becomes an `f64` payload and stops: a box
    /// endpoint, an error field, a report. Sound at a dual by
    /// delegation (`real.rs`'s DL5(a)) — a dual's bracket is its value
    /// channel's, so the payload is the base scalar's.
    Payload(&'static str),
    /// The read SELECTS among constructions whose classification is
    /// value-channel-decided and whose selected quantity is locally
    /// constant — DL5(b). The condition is load-bearing: this is the
    /// class `geom::projection_policy`'s `mid` freeze (#874) sits
    /// outside.
    Selection(&'static str),
    /// A blanket or per-scalar `impl` whose bound is the door itself
    /// rather than a consumer of it.
    Impl(&'static str),
    /// Another track's ground, with the row that owns it.
    HandedOff(&'static str),
}

/// One sole-bound site: where it is, what it is, and why it is sound.
///
/// Keyed on the SYMBOL, never on a line number — S88's own lesson, and
/// the reason its `profile` citations had gone stale by two merges.
struct Site {
    path: &'static str,
    subject: &'static str,
    why: Why,
}

