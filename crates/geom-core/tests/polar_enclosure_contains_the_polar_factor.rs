//! **The polar enclosure contains the true polar factor**
//! ([`Real::enclose_rotation`] at `Interval`, the lift of a stated frame
//! to an enclosure, `RigidMotion::map_scalar`).
//!
//! Each case's reference is the polar factor `R = M(MᵀM)^(−1/2)` of the
//! stated `M` (or of each sampled corner of a box of them), computed
//! offline to 80 significant digits by Newton's iteration
//! `X ← ½(X + X⁻ᵀ)` in exact decimal arithmetic, and stored as a
//! double-double: the nearest `f64` and the nearest `f64` to the rest.
//! Containment is decided exactly on that pair against the enclosure's
//! `f64` ends.
//!
//! The cases are rounded rotations (a rotation's entries rounded to
//! `f64`, so `M` is a rounding off rigid and `R` is not `M`), frames
//! stretched along one axis with `η = ‖MᵀM − I‖_F` up to 0.49, just
//! under the door's ½, and boxes of half-width 1e-6, 1e-3 and 0.05 on
//! every entry, sampled at twelve corners each.
//!
//! Red if the correction's sign is flipped (`M + ½·M·G`), if the stated
//! entries are read as points (the enclosure then misses `R` by the
//! rounding the stated frame is off rigid), or if the remainder bound is
//! dropped where `η` is large.
