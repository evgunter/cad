/// `lo ≤ h + l ≤ hi`, decided exactly for a double-double `(h, l)` whose
/// rest is at most half an ulp of `h`.
fn holds((lo, hi): (f64, f64), (h, l): (f64, f64)) -> bool {
    let above = lo < h || (lo == h && l >= 0.0);
    let below = h < hi || (h == hi && l <= 0.0);
    above && below
}

#[test]
fn the_polar_enclosure_contains_the_polar_factor() {
    let mut checked = 0;
    for case in CASES {
        let m = case.m.map(|col| {
            col.map(|x| Interval::from_bounds(x - case.half_width, x + case.half_width))
        });
        let Some(got) = <Interval as Real>::enclose_rotation(m) else {
            panic!("{}: Interval encloses no rotation of it", case.name);
        };
        for reference in case.polar {
            for j in 0..3 {
                for r in 0..3 {
                    let e = got[j][r];
                    assert!(
                        e.is_certified() && holds((e.lo(), e.hi()), reference[j][r]),
                        "{}: entry ({j}, {r}) [{:e}, {:e}] misses the polar factor's {:?}",
                        case.name,
                        e.lo(),
                        e.hi(),
                        reference[j][r]
                    );
                    checked += 1;
                }
            }
        }
    }
    assert_eq!(checked, 9 * (17 + 3 * 12), "every case's every entry read");
}
