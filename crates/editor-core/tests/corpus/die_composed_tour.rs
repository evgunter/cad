//! Corpus document **die_composed_tour** — the demo tour's composed
//! die, registered rather than re-transcribed.
//!
//! `die_composed` beside it is the surgery at its smallest honest
//! size: one pip, one rim, fourteen selected edges. The tour builds
//! the same surgery at the size a person actually sees — twenty-one
//! pips fused by ONE `Node::Union` into one grouped tool, then two
//! `Node::Fillet` sites over it: twelve box edges, and forty-two rim
//! arcs whose names carry the member each came from and nothing about
//! where it sits in the list. Every property the small document pins
//! holds here at a scale where a naming or selection defect has room
//! to show itself — and this is the document
//! `docm3_union::removing_any_pip_leaves_both_die_fillets_resolving`
//! drops a pip from, which is what the member keying is for.
//!
//! # Which of the tour's dice this is
//!
//! The scene's `build` authors THREE fillets, because it narrates
//! three stops and a stop renders one body. The third is the blank —
//! the same cube filleted with no pips cut. The document places the
//! composed die alone (`diefillet::gallery_document`); the blank stays
//! in the document as a value nothing places (DM4), so it is in no
//! product.
//!
//! Placing the blank as well puts a second die exactly on the first:
//! that product refuses `assemble` at `f64` with vertex-vertex
//! `UnrecordedContact` findings between the two dice, which would put
//! it in the divergence set `r2_m10_di_probes` pins — a row about
//! coincident copies inside a pin about the dual census door.
//!
//! # Why the document arrives as BYTES
//!
//! The authoring site is `demos/tour/src/diefillet.rs::build`, and it
//! stays the only one. That crate is a detached cargo workspace which
//! the kernel must never depend on, so there is no call to make: the
//! tour writes the document through its own `die-corpus` mode
//! (`diefillet::corpus_text`), the bytes are committed here, and this
//! module loads them. The alternative — a hand-transcribed twin —
//! is exactly what this document exists to retire, because a
//! transcription drifts silently and a byte file does not.
//!
//! Regenerate it with the tour's own door:
//!
//! ```text
//! cd demos/tour && cargo run --release -- die-corpus \
//!     ../../crates/editor-core/tests/corpus/tour/die_composed_tour.pncad
//! ```
//!
//! `ci.yml` runs exactly that line and diffs the result against the
//! committed file, so a scene change that moves the document is a red
//! run rather than a stale asset. That gate rides the tour job's
//! sampled row, not every code-tier run — see the PR that landed it.
//!
//! # Read at the process's ε
//!
//! A save records the ε it was written under, and `persist::load`
//! refuses it against a different process ε (one process, one ε —
//! `PersistError::ToleranceConflict`), while the registry is evaluated
//! at every CI ε row. So the file's one ε line is re-stamped to the
//! process's own before it loads, as `die_tool`'s committed document
//! is (`dm3_indexed_read`), and every row reads the same recipe under
//! its own ε. Nothing else in the file depends on ε: the document is
//! its recipe, and everything ε decides re-derives on evaluation.
//!
//! # The selections are FROZEN at the tour's tolerance
//!
//! Both geometric selections were materialized by the tour, under the
//! ε the file was generated at, and travel in the file as stored names.
//! Every ε row therefore blends the SAME fifty-four edges rather than
//! re-selecting per row — which is what a stored selection means
//! everywhere else in the registry (`Node::Fillet`'s payload docs), and
//! is the property the name-digest gate measures.
//!
//! # No mass pin
//!
//! π-valued closed forms are not dyadic — the `die_composed` /
//! `die_fillet` disposition. The tour's own stop meters the composed
//! volume against its closed form.

use std::path::Path;

use editor_core::{Coord, Node, ProfileDoc, RecipeNodeId, TargetAxis, load, save};
use geom_core::Tol;

use super::CorpusDoc;
use crate::fixture::value_bump;

/// The committed document, relative to the crate manifest. Read at
/// run time rather than `include_str!`d: the file is the tour's
/// OUTPUT, regenerated by the line named in [`loaded`], and reading it
/// at run time means regenerating it re-runs the rows without a
/// rebuild of the test binary that embeds it.
const FILE: &str = "tests/corpus/tour/die_composed_tour.pncad";

/// The label the tour authors under, and so the identity the committed
/// file must carry — checked, because a file under another label is a
/// different document with the same nodes.
const DOC_LABEL: &str = "die";

/// How far the top face's single pip slides along its pole axis,
/// meters (dyadic; a 1/64 slide, which keeps the whole cavity a cap on
/// its face and clear of the box-edge blend bands).
pub const PIP_SLIDE: f64 = 0.015625;

/// The tour's document, loaded from the committed save file.
///
/// # Panics
///
/// Loudly, on every arm: a missing file, an identity that is not
/// [`DOC_LABEL`]'s, or a body today's types cannot read. Each names the
/// regeneration line.
fn loaded() -> ProfileDoc {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(FILE);
    let recourse = "regenerate it: cd demos/tour && cargo run --release -- \
                    die-corpus ../../crates/editor-core/tests/corpus/tour/\
                    die_composed_tour.pncad";
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "the tour die document is missing ({}): {e} — {recourse}",
            path.display()
        )
    });
    // The whole file goes through the persistence layer's own loader,
    // so the id line and the body are read by the code that writes
    // them rather than by a second reader here, at the process's ε
    // (module docs).
    let tol = Tol::witness();
    let doc = load(&restamped_at_process_epsilon(&text), tol)
        .unwrap_or_else(|e| panic!("the tour die document refuses to load: {e:?} — {recourse}"));
    assert_eq!(
        doc.id(),
        ProfileDoc::empty_derived(DOC_LABEL, tol).id(),
        "the committed document is not the tour's `{DOC_LABEL}` document — {recourse}"
    );
    doc
}

/// `text` with its one `"epsilon":` line replaced by the line the
/// persistence layer writes for the process's own ε.
fn restamped_at_process_epsilon(text: &str) -> String {
    let tol = Tol::witness();
    let probe: ProfileDoc = ProfileDoc::empty_derived("tour-corpus-epsilon-probe", tol);
    let probe_text = save(&probe, tol).expect("an empty document saves");
    let is_epsilon = |line: &str| line.trim_start().starts_with("\"epsilon\":");
    let wanted = probe_text
        .lines()
        .find(|line| is_epsilon(line))
        .expect("a saved document records its ε");
    assert_eq!(
        text.lines().filter(|l| is_epsilon(l)).count(),
        1,
        "the tour die document carries exactly one ε line"
    );
    let mut out: String = text
        .lines()
        .map(|line| if is_epsilon(line) { wanted } else { line })
        .collect::<Vec<&str>>()
        .join("\n");
    out.push('\n');
    out
}

/// The first placement in the document — the +Z face's single pip,
/// which is the first placement the tour emits. Derived from the document
/// rather than transcribed as an id, so the bump follows the scene
/// instead of pinning a number that would go quietly wrong.
fn first_pip(doc: &ProfileDoc) -> RecipeNodeId {
    doc.ids()
        .iter()
        .copied()
        .find(|id| {
            matches!(
                doc.node(*id).expect("an ordered node exists"),
                Node::Place { .. }
            )
        })
        .expect("the die places its pips against its faces")
}

/// The tour's composed-die corpus document.
pub fn document() -> CorpusDoc {
    let doc = loaded();
    let Some(&placement) = doc.placements().last() else {
        panic!("the tour's die is placed in the world")
    };
    let Some(Node::Place { source, .. }) = doc.node(placement) else {
        unreachable!("the tour's placement copies its die")
    };
    let composed = doc
        .operation_of(source.read)
        .expect("the placed body is live");
    assert!(
        matches!(
            doc.node(composed).expect("the placed node"),
            Node::Fillet { .. }
        ),
        "the tour's die places the rim blend; if it no longer does, \
         this document's `result` names the wrong node"
    );
    let pip = first_pip(&doc);
    let bump = value_bump(&doc, pip, Coord::slide(TargetAxis::Z), PIP_SLIDE);

    CorpusDoc {
        name: "die_composed_tour",
        about: "the demo tour's die: 21 pips fused by one n-ary union and cut in one \
                grouped tool, then 12 box edges and 42 rim arcs blended behind \
                member-keyed names",
        // The file is the document's state: it carries no edits.
        edits: Vec::new(),
        doc,
        result: Some(composed),
        // π-valued closed forms are not dyadic — module docs.
        pin: None,
        // D2's incremental probe, `die_composed`'s bump at this
        // document's scale: slide the top face's pip along its pole
        // axis. The cube chain,
        // the master ball and the twenty other placements are reused;
        // the union tool, the cut and both surgeries recompute. The
        // slide mints and retires no edge, so both frozen selections
        // still resolve.
        //
        // The cone is FIVE nodes, and it used to be twenty-four: the
        // tool is one `Node::Union` now, so a bumped pip invalidates
        // that one node rather than every pairwise union standing
        // above it in a chain. The flat operator is what buys that —
        // the same fact the naming gets, counted in recompute.
        bump,
        bump_root: pip,
    }
}
