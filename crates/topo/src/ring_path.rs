//! **A ring lane's chart-free reading on a cylinder, a sphere, a cone
//! or a torus face**: the parity of a path on the face's surface across
//! a closed curve of loop arcs, which says whether the path's ends lie
//! on one side of the curve or on opposite sides.
//!
//! The path is made of pieces whose meeting with a loop arc is closed
//! form: on a cylinder or a cone, a segment of a ruling and an arc of a
//! parallel (the circle at one height), in either order, on a cone on
//! the ends' nappe and never through the apex; on a sphere, the short
//! great-circle arc between its ends; on a torus, an arc of a meridian
//! (the tube's circle at one azimuth) and an arc of a parallel, in
//! either order, after a segment that moves the start onto the tube
//! through the end, so the pieces meet exactly. A loop arc is a plane
//! section of the surface (a circle or an ellipse: no lane mints another
//! conic; on a torus, also a spiric oval), a ruling of a cylinder or a
//! cone, or a spline. So a piece meets a section arc only where it
//! crosses the arc's plane, which a circle piece does at most twice and
//! a segment once, and it meets a ruling only where the ruling crosses a
//! parallel's plane. Two rulings of a cone meet only at the apex, which
//! no piece reaches, and two of a cylinder nowhere unless they are one.
//! A piece meets a spline arc where the curve-pair table finds them
//! meeting ([`geom_brep::curve_pair::meet`]), each meeting decided a
//! crossing inside both spans.
//!
//! A plane cuts a torus in up to two loops, so on a torus a crossing of
//! an arc's plane lies on the arc's own loop only on that loop's side
//! of the split between the two ([`ArcLoop`]): a loop arc on a torus is
//! a meridian, a parallel or a spiric oval, whose plane's other loop is
//! the meridian across the axis, the parallel across the tube or the
//! oval across the axis's trace. The split
//! is decided at the crossing, **`split_ring_path_torus_loop`**, as the
//! boolean join's section loops are told apart.
//!
//! The tube's top and bottom circles (the parallels of radius `R`) are
//! the exception: their plane touches the torus along them, so a path
//! meets it only on the circle and never crosses it. They are read
//! across the cylinder `ρ = R` about the axis instead, which cuts the
//! torus transversally in exactly those two circles, told apart by their
//! height along the axis ([`LoopArc::Crest`]). A parallel piece keeps its
//! distance from the axis and a meridian piece crosses that cylinder at
//! the top and the bottom of the tube, through the plane through its
//! centre square to its radial, so each crossing is closed form too.
//!
//! The parity does not depend on the path where the curve is
//! null-homotopic where the paths run. Every closed curve on a sphere
//! is. A cylinder needs no such premise: it is an annulus, on which any
//! two closed curves cross an even number of times (the mod-2
//! intersection form of its first homology, generated by the circle
//! round the axis, is zero, since that circle is pushed off itself along
//! the axis), so two paths with the same ends cross any closed curve
//! alike; and an embedded closed curve on it, winding round the axis
//! (a drum wall's section loop, which goes all the way round) or not,
//! separates it. Which side of it is the region a curve bounds is the
//! curve's to say only where it does not wind: there it bounds a disc.
//! So a parity read as membership of a cylinder face's region (the ring
//! re-homing's) rests on the face being a disc of the chart, no loop of
//! it winding round the axis, as on a cone and a torus; a run that
//! winds (a seamless band's) bounds no disc, and its side would be read
//! off its orientation, which the parity does not see. On a cone, the paths run on the punctured nappe, an annulus, and
//! the curve bounds a disc of it: it lies on one face, and no loop of the
//! face winds round the axis, so no curve on it winds round the apex. On
//! a torus, the paths run anywhere on it and the curve bounds a disc: it
//! lies on one face, no loop of which winds round either period, so the
//! face lifts to a disc of the chart plane and a closed curve on it
//! lifts closed. A loop that does not wind is one whose chart walk closes
//! on its start, its deck elements composed to the identity
//! (`pcurves::loop_windings`' `zero`); nothing about how far the loop
//! spans the chart enters, and the at-rest pass does not yet refuse a
//! loop that winds (`work/pctail/a-seamless-band-mints-and-passes-tier-3-though-loopwraps-says-no-constructor-makes-one.md`). The parity of a path
//! across a curve that bounds is its ends' sides of the disc, whichever
//! way round the tube or the axis it goes.
//!
//! Each decision is a named trilean metered in metres. The raw picks
//! that remain — the nearer root on the arrival arc, a parameter's
//! branch, the way round a parallel — are choices every outcome of which
//! is sound, each argued at its site. A crossing is
//! passed over once any reading is decided against it, whatever its
//! other readings say: a decided rejection is decided. A reading of a
//! crossing not passed over that lands in the zero band — the path
//! grazes an arc, runs through an arc's end, or starts on an arc's
//! plane — makes the path undecided, one in the escalation band makes
//! it escalate, and the caller asks another.

use geom_core::{Band, Decide, Indeterminate, Margin, Point3, Real, Sign, Vec3};

use crate::validate::decide;

/// The surface a path runs on: the kinds the ring lane reads without a
/// chart.
#[derive(Clone, Copy)]
pub(crate) enum Quadric<T: Real> {
    Cylinder {
        origin: Point3<T>,
        axis: Vec3<T>,
        radius: T,
    },
    Sphere {
        centre: Point3<T>,
        radius: T,
    },
    Cone {
        apex: Point3<T>,
        axis: Vec3<T>,
        half_angle: T,
    },
    Torus {
        centre: Point3<T>,
        axis: Vec3<T>,
        major: T,
        minor: T,
    },
}

impl<T: Decide> Quadric<T> {
    /// The quadric of `surface`; `None` for any other kind.
    pub(crate) fn of(surface: &geom::Surface<T>) -> Option<Self> {
        match *surface {
            geom::Surface::Cylinder {
                origin,
                axis,
                radius,
                ..
            } => Some(Self::Cylinder {
                origin,
                axis,
                radius,
            }),
            geom::Surface::Sphere { center, radius, .. } => Some(Self::Sphere {
                centre: center,
                radius,
            }),
            geom::Surface::Cone {
                apex,
                axis,
                half_angle,
                ..
            } => Some(Self::Cone {
                apex,
                axis,
                half_angle,
            }),
            geom::Surface::Torus {
                center,
                axis,
                major_radius,
                minor_radius,
                ..
            } => Some(Self::Torus {
                centre: center,
                axis,
                major: major_radius,
                minor: minor_radius,
            }),
            _ => None,
        }
    }

    /// `p`'s height along a cone's axis and its offset from the axis.
    fn axial(apex: Point3<T>, axis: Vec3<T>, p: Point3<T>) -> (T, Vec3<T>) {
        let w = p - apex;
        let h = w.dot(axis);
        (h, w - axis * h)
    }

    /// The length a dimensionless reading at `p` is levered by: the
    /// cylinder's or the sphere's radius, the radius of the cone's parallel through `p`, or
    /// the torus's tube radius or its parallel's through `p`, whichever
    /// is smaller.
    pub(crate) fn lever(&self, p: Point3<T>) -> T {
        match *self {
            Self::Cylinder { radius, .. } => radius.abs(),
            Self::Sphere { radius, .. } => radius,
            Self::Cone { apex, axis, .. } => Self::axial(apex, axis, p).1.norm(),
            Self::Torus {
                centre,
                axis,
                minor,
                ..
            } => minor.min(Self::axial(centre, axis, p).1.norm()),
        }
    }

    /// The chart normal at `p` (the outward one for a face of sense
    /// `true`): the cylinder's or the sphere's radial direction, or the cone's
    /// `ŵ·cos α − â·sin α·sgn h`, `ŵ` the radial direction. `p` is off a
    /// cone's apex ([`Self::off_apex`]); on a torus, the direction from
    /// the core circle's nearest point, off the axis and the core.
    fn chart_normal(&self, p: Point3<T>) -> Vec3<T> {
        match *self {
            Self::Cylinder {
                origin,
                axis,
                radius,
            } => Self::axial(origin, axis, p).1 / radius,
            Self::Sphere { centre, radius } => (p - centre) / radius,
            Self::Cone {
                apex,
                axis,
                half_angle,
            } => {
                let (h, w) = Self::axial(apex, axis, p);
                let (s, c) = half_angle.sin_cos();
                w / w.norm() * c - axis * h.select_le_zero(-s, s)
            }
            Self::Torus {
                centre,
                axis,
                major,
                ..
            } => {
                let tube = p - Self::core(centre, axis, major, p);
                tube / tube.norm()
            }
        }
    }

    /// The core circle's point at `p`'s azimuth, `p` off the axis.
    fn core(centre: Point3<T>, axis: Vec3<T>, major: T, p: Point3<T>) -> Point3<T> {
        let w = Self::axial(centre, axis, p).1;
        centre + w / w.norm() * major
    }

    /// The outward normal at `p` of a face of sense `sense`
    /// ([`Self::chart_normal`] folded by the sense).
    pub(crate) fn outward(&self, p: Point3<T>, sense: bool) -> Vec3<T> {
        geom_brep::OutwardNormal::from_chart(self.chart_normal(p), sense).vec()
    }

    /// Whether `p` is decided off a cone's apex or a torus's axis (its
    /// distance from the axis, **`split_ring_path_off_apex`**, charged
    /// the two points' [`resolution`]): always on a cylinder and a
    /// sphere.
    pub(crate) fn off_apex(&self, p: Point3<T>, band: Band) -> Result<bool, Indeterminate> {
        match *self {
            Self::Cylinder { .. } | Self::Sphere { .. } => Ok(true),
            Self::Cone { apex, axis, .. }
            | Self::Torus {
                centre: apex, axis, ..
            } => Ok(decide(
                "split_ring_path_off_apex",
                Margin::of(charge(
                    Self::axial(apex, axis, p).1.norm(),
                    resolution(&[apex, p]),
                )),
                band,
            )? == Sign::Positive),
        }
    }

    /// **The paths from `from` to `to`** this quadric reads, in the order
    /// they are asked; none where no path is decided to exist. Each
    /// reading below is charged the [`resolution`] of the ends and the
    /// quadric's centre or apex ([`charge`]).
    ///
    /// - A cylinder's are its two ruled paths ([`Self::ruled_paths`]).
    /// - A sphere's is the short great-circle arc, which exists when the
    ///   ends are decided neither equal nor antipodal
    ///   (**`split_ring_path_span`**: the sine between them, levered at
    ///   the radius).
    /// - A cone's are its two ruled paths ([`Self::ruled_paths`]), on the
    ///   ends' one nappe (each end's height along the axis decided
    ///   nonzero and of one sign, **`split_ring_path_nappe`**) and off
    ///   the apex. The arrival across the closing arc's section is
    ///   transversal on one of them wherever it is on either.
    /// - A torus's are two, from ends decided off the axis and off the
    ///   core circle (**`split_ring_path_off_core`**: the distance from
    ///   it). Each first moves `from` along its tube radius onto the
    ///   tube through `to` (a segment, as short as the ends' offsets off
    ///   the carrier), then runs round that tube's meridian through the
    ///   start to `to`'s parallel and round it, arriving along the
    ///   parallel; or round the start's parallel to `to`'s meridian and
    ///   round it, arriving along the meridian. A meridian loop arc
    ///   holds the first's arrival transversal and a parallel the
    ///   second's.
    pub(crate) fn paths(
        &self,
        (from, to): (Point3<T>, Point3<T>),
        band: Band,
    ) -> Result<Vec<Path<T>>, Indeterminate> {
        match *self {
            Self::Cylinder { origin, axis, .. } => self.ruled_paths(
                (origin, axis),
                (from, to),
                resolution(&[from, to, origin]),
                band,
            ),
            Self::Sphere { centre, radius } => {
                let slack = resolution(&[from, to, centre]);
                let a = (from - centre) / radius;
                let b = (to - centre) / radius;
                let m = a.cross(b);
                let sine = m.norm();
                if decide(
                    "split_ring_path_span",
                    Margin::levered(charge(sine, slack / radius), radius),
                    band,
                )? != Sign::Positive
                {
                    return Ok(Vec::new());
                }
                let axis = m / sine;
                let arc = CircleArc {
                    centre,
                    axis,
                    radius,
                    u_ref: a,
                    span: (T::zero(), sine.atan2(a.dot(b))),
                };
                Ok(vec![Path {
                    pieces: vec![Piece::Arc(arc)],
                    arrival: axis.cross(b),
                }])
            }
            Self::Cone { apex, axis, .. } => {
                if !self.off_apex(from, band)? || !self.off_apex(to, band)? {
                    return Ok(Vec::new());
                }
                let slack = resolution(&[from, to, apex]);
                let nappe = |p| {
                    decide(
                        "split_ring_path_nappe",
                        Margin::of(charge(Self::axial(apex, axis, p).0, slack)),
                        band,
                    )
                };
                let side = nappe(from)?;
                if side == Sign::Zero || nappe(to)? != side {
                    return Ok(Vec::new());
                }
                self.ruled_paths((apex, axis), (from, to), slack, band)
            }
            Self::Torus {
                centre,
                axis,
                major,
                ..
            } => {
                if !self.off_apex(from, band)? || !self.off_apex(to, band)? {
                    return Ok(Vec::new());
                }
                let core = |p| Self::core(centre, axis, major, p);
                let (kf, kt) = (core(from), core(to));
                let (off_f, off_t) = ((from - kf).norm(), (to - kt).norm());
                let slack = resolution(&[from, to, centre]);
                for off in [off_f, off_t] {
                    if decide(
                        "split_ring_path_off_core",
                        Margin::of(charge(off, slack)),
                        band,
                    )? != Sign::Positive
                    {
                        return Ok(Vec::new());
                    }
                }
                // Every piece lies on the tube of radius `off_t` about the
                // core, through `to`: `from` is moved onto it first, along
                // its own tube radius, so each turn is placed on the circle
                // the next piece runs round and the pieces meet exactly,
                // as the cone's do.
                let start = kf + (from - kf) * (off_t / off_f);
                // The ruling and lever are read only against a `Line` loop
                // arc, and no loop arc on a torus is one
                // ([`Self::torus_circle_arc`] yields conics and crests).
                let lead = Piece::Segment {
                    from,
                    to: start,
                    ruling: Vec3::zero(),
                    lever: T::zero(),
                };
                let radial = |k: Point3<T>| (k - centre) / major;
                let (ef, et) = (radial(kf), radial(kt));
                let (hs, ws) = Self::axial(centre, axis, start);
                let (ht, wt) = Self::axial(centre, axis, to);
                let (rs, rt) = (ws.norm(), wt.norm());
                let mut paths = Vec::with_capacity(2);
                // Round the start's meridian to `to`'s parallel, then round.
                let turned = centre + axis * ht + ef * rt;
                let meridian = parallel(kf, ef.cross(axis), off_t, start, turned);
                let round = parallel(centre + axis * ht, axis, rt, turned, to);
                paths.push(Path {
                    pieces: vec![lead, Piece::Meridian(meridian), Piece::Arc(round)],
                    arrival: round.tangent(round.span.1),
                });
                // Round the start's parallel to `to`'s meridian, then round.
                let turned = centre + axis * hs + et * rs;
                let round = parallel(centre + axis * hs, axis, rs, start, turned);
                let meridian = parallel(kt, et.cross(axis), off_t, turned, to);
                paths.push(Path {
                    pieces: vec![lead, Piece::Arc(round), Piece::Meridian(meridian)],
                    arrival: meridian.tangent(meridian.span.1),
                });
                Ok(paths)
            }
        }
    }
}

impl<T: Decide> Quadric<T> {
    /// **The two paths of a ruled quadric**, a cylinder or a cone, from
    /// `from` to `to`, with `base` its origin or apex and `axis` its
    /// axis, each reading charged `slack`:
    ///
    /// - along `from`'s ruling to `to`'s height and round that parallel,
    ///   arriving along the parallel, where the parallel's arc is decided
    ///   of some length (**`split_ring_path_turn`**: the arc's length);
    /// - round `from`'s parallel to `to`'s ruling and along it, arriving
    ///   along the ruling, where the length along `to`'s ruling from the
    ///   turn to `to` is decided nonzero (**`split_ring_path_rise`**:
    ///   the height difference on a cylinder, the slant difference on a
    ///   cone).
    ///
    /// A path is asked only where the piece it arrives along has a length,
    /// so its arrival is a direction it travels; its first piece may have
    /// none, and is kept so the pieces meet exactly. Each turn is placed on the parallel the next
    /// piece runs round, at that parallel's own radius, so the pieces meet
    /// exactly: the ends lie on the carrier only up to the band, and a
    /// turn at the carrier's ratio would leave a gap of that offset at
    /// the seam, where a crossing could go uncounted. A ruling piece then
    /// leans off its ruling by the same offset: its crossings of a
    /// section are read from its ends, and the rulings-apart readings are
    /// decided past the band that offset lies in.
    fn ruled_paths(
        &self,
        (base, axis): (Point3<T>, Vec3<T>),
        (from, to): (Point3<T>, Point3<T>),
        slack: T,
        band: Band,
    ) -> Result<Vec<Path<T>>, Indeterminate> {
        let (hf, wf) = Self::axial(base, axis, from);
        let (ht, wt) = Self::axial(base, axis, to);
        let (rf, rt) = (wf.norm(), wt.norm());
        let (uf, ut) = (wf / rf, wt / rt);
        let turned = base + axis * ht + uf * rt;
        let below = base + axis * hf + ut * rf;
        // The length along `to`'s ruling from the turn to `to`, and that
        // ruling's unit direction, along which the second path arrives.
        let (rise, ruling_at_to) = match *self {
            Self::Cone { .. } => {
                let e = to - base;
                (e.norm() - (below - base).norm(), e / e.norm())
            }
            _ => (ht - hf, axis),
        };
        // A ruling piece from `a` to `b` on the ruling through `on`.
        let piece = |a: Point3<T>, b: Point3<T>, on: Point3<T>| match *self {
            Self::Cone { .. } => {
                let e = on - base;
                Piece::Segment {
                    from: a,
                    to: b,
                    ruling: e / e.norm(),
                    lever: e.norm(),
                }
            }
            _ => Piece::Ruling { from: a, to: b },
        };
        let rise = decide(
            "split_ring_path_rise",
            Margin::of(charge(rise, slack)),
            band,
        )?;
        let round_at_to = parallel(base + axis * ht, axis, rt, turned, to);
        let turn = decide(
            "split_ring_path_turn",
            Margin::of(charge(
                (round_at_to.span.1 - round_at_to.span.0) * rt,
                slack,
            )),
            band,
        )?;
        let mut paths = Vec::with_capacity(2);
        if turn != Sign::Zero {
            paths.push(Path {
                pieces: vec![piece(from, turned, from), Piece::Arc(round_at_to)],
                arrival: round_at_to.tangent(round_at_to.span.1),
            });
        }
        if rise != Sign::Zero {
            let round = parallel(base + axis * hf, axis, rf, from, below);
            paths.push(Path {
                pieces: vec![Piece::Arc(round), piece(below, to, to)],
                arrival: if rise == Sign::Positive {
                    ruling_at_to
                } else {
                    -ruling_at_to
                },
            });
        }
        Ok(paths)
    }
}

/// The arc of the circle centred `centre` about the unit `axis`, of
/// radius `radius`, from `from` to `to` (both in its plane), the short
/// way round: a parallel, or a torus's meridian.
fn parallel<T: Decide>(
    centre: Point3<T>,
    axis: Vec3<T>,
    radius: T,
    from: Point3<T>,
    to: Point3<T>,
) -> CircleArc<T> {
    let u = from - centre;
    let u = u / u.norm();
    let w = to - centre;
    let phi = w.dot(axis.cross(u)).atan2(w.dot(u));
    // The way round is a raw pick: either is a path between the same
    // ends, and the parity is the same on every path.
    CircleArc {
        centre,
        axis: axis * phi.select_le_zero(-T::one(), T::one()),
        radius,
        u_ref: u,
        span: (T::zero(), phi.abs()),
    }
}

/// A circle arc, travelled with its parameter over the increasing
/// `span`: `centre + (u_ref·cos t + (axis × u_ref)·sin t)·radius`.
#[derive(Clone, Copy)]
struct CircleArc<T: Real> {
    centre: Point3<T>,
    axis: Vec3<T>,
    radius: T,
    u_ref: Vec3<T>,
    span: (T, T),
}

impl<T: Real> CircleArc<T> {
    fn v_ref(&self) -> Vec3<T> {
        self.axis.cross(self.u_ref)
    }

    fn at(&self, t: T) -> Point3<T> {
        let (s, c) = t.sin_cos();
        self.centre + (self.u_ref * c + self.v_ref() * s) * self.radius
    }

    /// The unit direction of travel at `t`.
    fn tangent(&self, t: T) -> Vec3<T> {
        let (s, c) = t.sin_cos();
        self.v_ref() * c - self.u_ref * s
    }

    /// The parameter of `p` (a point of the circle) on the branch of the
    /// span's middle.
    fn param(&self, p: Point3<T>) -> T {
        let w = p - self.centre;
        branch(w.dot(self.v_ref()).atan2(w.dot(self.u_ref)), self.span)
    }
}

/// `t` moved by whole turns to the branch of `span`'s middle, into
/// `(mid − τ/2, mid + τ/2]`.
///
/// **The window re-centring argument**, which the sites that re-centre
/// a parameter on a span's middle and read it only against the span's
/// ends cite. A raw pick, sound whichever way it falls. A parameter
/// inside the span lies within half the span of the middle and lands on
/// its own branch. Only a parameter half a turn from the middle is in
/// doubt:
/// - on a span shorter than a turn (a piece's), it is outside the span
///   on either branch, by at least half the span's complement;
/// - on a whole-turn span (a loop arc over a closed edge, or a
///   self-loop chord's `ArcEnd::WholeTurn`), it IS the span's end, `lo`
///   and `hi` being one point. This spelling lands it on `hi`, the
///   `reduce_periodic_centred` spelling on `lo`, and every reader of an
///   end reads `lo` and `hi` alike (here `in_span` decides Zero at
///   either end and the path says nothing).
///
/// Over the scalars:
/// - at `f64` the half-turn parameter is reached (adversarial path grids
///   do) and lands as above;
/// - at `Interval` an enclosure straddling it spans both branches and
///   the in-span reading escalates or declines. On a closed circle a
///   seam-vertex root escalates hard (`boolean::reduce`'s
///   `bool_wall_root_in_span`);
/// - at `Sym` the `floor` folds only where its argument's form is the
///   zero polynomial, the exact tie, where the fold is the true `⌊0⌋`
///   and agrees with `f64`. Elsewhere it is an atom keyed by its
///   argument's form, so floors of form-equal arguments cancel, and a
///   reading is numeric unless such a fold or cancellation makes it an
///   identity.
///
/// No reader reads the pick as an identity: the parameter is compared
/// only with span ends of another provenance.
fn branch<T: Real>(t: T, (lo, hi): (T, T)) -> T {
    let mid = (lo + hi) * T::from_f64(0.5);
    let tau = T::tau();
    t + (mid - t).periodic_branch(tau) * tau
}

/// A piece of a [`Path`].
#[derive(Clone, Copy)]
enum Piece<T: Real> {
    /// An arc of a great circle, or of a parallel of a cone or a torus.
    Arc(CircleArc<T>),
    /// An arc of a torus's meridian (a circle round the tube, in a plane
    /// holding the axis).
    Meridian(CircleArc<T>),
    /// A segment of a cylinder's ruling.
    Ruling { from: Point3<T>, to: Point3<T> },
    /// A segment of the cone's ruling `ruling` (unit, from the apex),
    /// whose distance from the apex at `from` is `lever`.
    Segment {
        from: Point3<T>,
        to: Point3<T>,
        ruling: Vec3<T>,
        lever: T,
    },
}

/// A path on a [`Quadric`] between two points, and its unit direction
/// of travel where it arrives.
pub(crate) struct Path<T: Real> {
    pieces: Vec<Piece<T>>,
    pub(crate) arrival: Vec3<T>,
}

/// An arc of a section conic over its increasing span:
/// `centre + u_ref·a·cos t + (axis × u_ref)·b·sin t`, `a = b` on a
/// circle.
#[derive(Clone, Copy)]
pub(crate) struct Conic<T: Real> {
    centre: Point3<T>,
    axis: Vec3<T>,
    u_ref: Vec3<T>,
    a: T,
    b: T,
    span: (T, T),
    /// On a torus, the side of its plane's two loops the conic's own
    /// circle lies on; `None` where the plane cuts the surface in the
    /// conic alone.
    own: Option<ArcLoop<T>>,
}

/// An arc of a spiric oval on a torus over its increasing span
/// (`centre + u_ref·offset + m·f(t) + axis·minor·sin t`,
/// `m = axis × u_ref`, `f = √((major + minor·cos t)² − offset²)`, the
/// carrier's own form): one of the two loops its plane parallel to the
/// axis cuts, on the `+m` side of the axis's trace (`own`). Its
/// parameter is the torus's minor angle at a point, and its speed in it
/// is at least `minor`.
#[derive(Clone, Copy)]
pub(crate) struct Oval<T: Real> {
    centre: Point3<T>,
    axis: Vec3<T>,
    u_ref: Vec3<T>,
    major: T,
    minor: T,
    offset: T,
    span: (T, T),
    /// The side of its plane's two loops the oval's own lies on; `None`
    /// only where a row strips it to show what it guards.
    own: Option<ArcLoop<T>>,
}

/// An arc of a loop on a cylinder, sphere, cone or torus face, over its
/// increasing span: a section conic, a spiric oval, a ruling
/// (`origin + dir·t`) or a spline.
#[derive(Clone)]
pub(crate) enum LoopArc<T: Real> {
    Conic(Conic<T>),
    Line {
        origin: Point3<T>,
        dir: Vec3<T>,
        span: (T, T),
    },
    Oval(Oval<T>),
    /// An arc of a torus's top or bottom circle, the parallel of radius
    /// `R` (`centre + (u_ref·cos t + (axis × u_ref)·sin t)·radius`),
    /// whose plane touches the torus along it. A path meets it only where
    /// it crosses the cylinder `ρ = R` about the torus's axis, which cuts
    /// the torus transversally in this circle and the one across the tube
    /// (`own` tells them apart by the height along the axis).
    Crest {
        centre: Point3<T>,
        axis: Vec3<T>,
        u_ref: Vec3<T>,
        radius: T,
        span: (T, T),
        /// The torus's centre, unit axis and major radius `R`.
        core: (Point3<T>, Vec3<T>, T),
        own: ArcLoop<T>,
    },
    /// An arc of a spline carrier known to lie on the face's surface
    /// ([`SplineArc`]), whose meetings with a path's piece are the
    /// curve-pair table's ([`geom_brep::curve_pair::meet`]).
    Spline(SplineArc<T>),
}

/// **A spline arc on a cylinder, a sphere or a torus face, with the
/// evidence that it lies on the face's surface to within the band.**
///
/// [`spline_crossings`] reads a spline arc's meetings with a path's
/// pieces through the curve-pair table, which finds the points where
/// two curves meet in space. A path lies on the surface and a crossing of
/// the arc on the surface is a meeting in space only where the arc lies
/// on the surface too: an arc standing off it by more than the band
/// passes near the path instead and is read as missing it, which
/// miscounts the parity. So a spline arc is made only where that
/// distance is certified, by one of two constructors:
///
/// - [`Self::of_edge`]: a certified edge whose description is the
///   intersection of the face's surface with another, which the edge
///   door certified by C2's limb 2 against each (its distance zero in
///   the band);
/// - [`Self::of_section`]: an arc of a component the general rung fitted
///   with its three-limb certificate against both surfaces of the
///   section, the chord a join is about to mint from it.
///
/// Both are read on a cylinder, a sphere or a torus face: the faces a
/// carried chord bounds, which the ring lane's rows read
/// (`ring_path::tests`). Every piece of a torus path past its lead lies
/// on the tube through its end, within the band of the face's own, so the
/// argument is the cylinder's: a crossing on the surface is a meeting in
/// space. The lead, which moves the start onto that tube along its own
/// tube radius, is off the surface but no longer than the two ends'
/// offsets from it, within the band: an arc meeting it meets it within
/// the band of the path's start, which the curve-pair table reads at the
/// lead's span end, and there the path says nothing ([`spline_crossings`])
/// and the caller asks another.
#[derive(Clone)]
pub(crate) struct SplineArc<T: Real> {
    carrier: geom::Curve3<T>,
    span: (T, T),
}

impl<T: Real> SplineArc<T> {
    fn spline(carrier: &geom::Curve3<T>, (t0, t1): (T, T)) -> Option<Self> {
        matches!(carrier, geom::Curve3::Nurbs(_)).then(|| Self {
            carrier: carrier.clone(),
            span: (t0.min(t1), t0.max(t1)),
        })
    }

    /// The arc of `curve`, a certified spline edge described as the
    /// intersection of `surface` (the face's) and another; `None` for
    /// any other edge.
    pub(crate) fn of_edge(
        curve: &geom_brep::EdgeCurve<T>,
        surface: crate::geometry::SurfaceKey,
    ) -> Option<Self> {
        match curve.description() {
            geom_brep::EdgeDescription::Intersection { pair, .. } if pair.contains(surface) => {
                Self::spline(curve.carrier(), curve.params())
            }
            _ => None,
        }
    }

    /// The arc of `carrier` over `params`, cut from `component`, a
    /// fitted component of a section of the face's surface; `None` for a
    /// component with no certificate.
    pub(crate) fn of_section(
        component: &geom_brep::CarriedComponent<T>,
        carrier: &geom::Curve3<T>,
        params: (T, T),
    ) -> Option<Self> {
        component
            .certificate
            .as_ref()
            .and_then(|_| Self::spline(carrier, params))
    }

    /// A fixture's arc, whose spline lies on the surface by construction.
    #[cfg(test)]
    pub(crate) fn on_by_construction(carrier: &geom::Curve3<T>, params: (T, T)) -> Option<Self> {
        Self::spline(carrier, params)
    }
}

impl<T: Real> LoopArc<T> {
    /// The arc of `carrier` between the parameters `t0` and `t1`;
    /// `None` on a spiric, which only a torus carries
    /// ([`Quadric::torus_spiric_arc`]), and on a spline, which carries
    /// its evidence ([`SplineArc`]).
    pub(crate) fn of(carrier: &geom::Curve3<T>, (t0, t1): (T, T)) -> Option<Self> {
        let span = (t0.min(t1), t0.max(t1));
        match *carrier {
            geom::Curve3::Circle {
                center,
                axis,
                radius,
                u_ref,
            } => Some(Self::Conic(Conic {
                centre: center,
                axis,
                u_ref,
                a: radius,
                b: radius,
                span,
                own: None,
            })),
            geom::Curve3::Ellipse {
                center,
                axis,
                semi_u,
                semi_v,
                u_ref,
            } => Some(Self::Conic(Conic {
                centre: center,
                axis,
                u_ref,
                a: semi_u,
                b: semi_v,
                span,
                own: None,
            })),
            geom::Curve3::Line { origin, dir } => Some(Self::Line { origin, dir, span }),
            geom::Curve3::Nurbs(_) | geom::Curve3::Spiric { .. } => None,
        }
    }

    /// The straight arc from `from` to `to`.
    pub(crate) fn segment(from: Point3<T>, to: Point3<T>) -> Self {
        let d = to - from;
        let length = d.norm();
        Self::Line {
            origin: from,
            dir: d / length,
            span: (T::zero(), length),
        }
    }
}

impl<T: Decide> LoopArc<T> {
    /// **A section arc's plane and its reading at a point of it**, for
    /// a conic or a spiric oval: the plane (a point of it and its unit
    /// normal), the arc's span, the least speed of its parameter (metres
    /// per radian: a conic's minor semi-axis, an oval's tube radius),
    /// which levers an in-span reading, and the side of its plane's two
    /// loops its own lies on. `None` for a ruling or a crest.
    fn plane(&self) -> Option<SectionArc<T>> {
        match *self {
            Self::Conic(c) => Some(SectionArc {
                origin: c.centre,
                normal: c.axis,
                span: c.span,
                // The conic's least speed, its smaller semi-axis: the
                // seam may sit at either principal vertex.
                speed: c.a.abs().min(c.b.abs()),
                own: c.own,
            }),
            Self::Oval(o) => Some(SectionArc {
                origin: o.centre + o.u_ref * o.offset,
                normal: o.u_ref,
                span: o.span,
                speed: o.minor,
                own: o.own,
            }),
            Self::Line { .. } | Self::Crest { .. } | Self::Spline { .. } => None,
        }
    }

    /// The parameter of `x`, a point of a section arc's plane, on the
    /// branch of its span's middle ([`Conic::param`], [`Oval::param`]).
    /// A ruling or a crest has none.
    fn param_at(&self, x: Point3<T>) -> Option<T> {
        match *self {
            Self::Conic(c) => Some(c.param(x)),
            Self::Oval(o) => Some(o.param(x)),
            Self::Line { .. } | Self::Crest { .. } | Self::Spline { .. } => None,
        }
    }
}

impl<T: Decide> Oval<T> {
    /// The oval's carrier.
    fn carrier(&self) -> geom::Curve3<T> {
        geom::Curve3::Spiric {
            center: self.centre,
            axis: self.axis,
            u_ref: self.u_ref,
            major_radius: self.major,
            minor_radius: self.minor,
            offset: self.offset,
        }
    }

    /// The parameter of `x`, a point of the oval's plane, on the branch
    /// of its span's middle: the carrier's own reading.
    fn param(&self, x: Point3<T>) -> T {
        let mid = (self.span.0 + self.span.1) * T::from_f64(0.5);
        match self.carrier().param_near(x, mid) {
            Some(t) => t,
            None => unreachable!("a spiric carrier reads every point's parameter"),
        }
    }
}

/// A section arc's plane and the length its in-span readings are
/// levered by ([`LoopArc::plane`]).
#[derive(Clone, Copy)]
struct SectionArc<T: Real> {
    origin: Point3<T>,
    normal: Vec3<T>,
    span: (T, T),
    speed: T,
    own: Option<ArcLoop<T>>,
}

/// **Which of two loops of one plane section a point lies on**: the sign
/// of a margin in metres, definite at every point of a served section.
/// The boolean join reads it at a germ site (`boolean::join`'s
/// `SectionLoops`), and the ring lane at a crossing of a torus loop
/// arc's plane ([`ArcLoop`]).
#[derive(Clone, Copy, Debug)]
pub(crate) enum LoopSplit<T: Real> {
    /// `(p − origin)·dir`, `dir` unit.
    Side {
        /// A point of the plane between the loops.
        origin: Point3<T>,
        /// That plane's unit normal.
        dir: Vec3<T>,
    },
    /// `p`'s distance from the axis `(origin, axis)` less `radius`,
    /// `axis` unit.
    Radius {
        /// A point of the axis.
        origin: Point3<T>,
        /// The axis.
        axis: Vec3<T>,
        /// The radius between the loops.
        radius: T,
    },
    /// `|(p − origin)·sum| − |(p − origin)·diff|`, `sum` and `diff`
    /// unit: two equal cylinders with unit axes `â₁`, `â₂` meeting at
    /// `origin` cut each other in two ellipses, one in each bisector
    /// plane through `origin`, the first with normal `diff =
    /// unit(â₁ − â₂)`, the second `sum = unit(â₁ + â₂)`. A point of the
    /// first has `(p − origin)·diff = 0` and of the second `(p −
    /// origin)·sum = 0`, so the margin is positive on the first and
    /// negative on the second, its distance from the other bisector
    /// plane, and zero only on the planes' common line, where the
    /// ellipses cross (the nodes).
    Bisector {
        /// The axes' meeting point.
        origin: Point3<T>,
        /// `unit(â₁ + â₂)`.
        sum: Vec3<T>,
        /// `unit(â₁ − â₂)`.
        diff: Vec3<T>,
    },
}

impl<T: Real> LoopSplit<T> {
    /// The margin at `p`: positive on the split's positive loop.
    pub(crate) fn margin(&self, p: Point3<T>) -> T {
        match *self {
            Self::Side { origin, dir } => (p - origin).dot(dir),
            Self::Radius {
                origin,
                axis,
                radius,
            } => (p - origin).cross(axis).norm() - radius,
            Self::Bisector { origin, sum, diff } => {
                (p - origin).dot(sum).abs() - (p - origin).dot(diff).abs()
            }
        }
    }

    /// **The split of a plane×torus section's two loops**, the one
    /// reading the boolean join's frame (`boolean::join`'s
    /// `pt_germ_frame`) and the chord (`chord_join::section_case`) both
    /// take, so that they name one loop. The torus is `(centre, axis,
    /// R)` and `n` the plane's normal.
    ///
    /// - The meridian circles and the spiric ovals: the side of the
    ///   plane through the axis square to the cut, the first loop on the
    ///   positive side.
    /// - The concentric circles: the distance from the axis against `R`,
    ///   the outer circle positive.
    ///
    /// `None` for a section with no two loops, or a meridian section
    /// whose first loop is no circle.
    pub(crate) fn plane_torus(
        section: &geom_brep::PlaneTorusSection<T>,
        (centre, axis, major): (Point3<T>, Vec3<T>, T),
        n: Vec3<T>,
    ) -> Option<Self> {
        match section {
            geom_brep::PlaneTorusSection::MeridianCircles {
                c1: geom::Curve3::Circle { center, .. },
                ..
            } => Some(Self::Side {
                origin: centre,
                dir: (*center - centre).normalize(),
            }),
            geom_brep::PlaneTorusSection::SpiricOvals { .. } => Some(Self::Side {
                origin: centre,
                dir: axis.cross(n).normalize(),
            }),
            geom_brep::PlaneTorusSection::ConcentricCircles { .. } => Some(Self::Radius {
                origin: centre,
                axis: axis.normalize(),
                radius: major,
            }),
            geom_brep::PlaneTorusSection::MeridianCircles { .. }
            | geom_brep::PlaneTorusSection::TangentCircle(_)
            | geom_brep::PlaneTorusSection::Empty => None,
        }
    }
}

/// **Which of its plane's two loops on a torus a loop arc's circle is**:
/// the split between them and the circle's side of it. A meridian's
/// plane holds the axis and cuts the meridian across it too, `2(R − r)`
/// or more away: the split is the plane through the axis square to it,
/// the circle on the side of `ê`, toward its centre. A parallel's plane
/// cuts the parallel across the tube: the split is the core radius `R`,
/// the outer parallel on its positive side. Both are the boolean join's
/// loop splits for those sections.
#[derive(Clone, Copy)]
pub(crate) struct ArcLoop<T: Real> {
    split: LoopSplit<T>,
    /// Whether the arc's circle is on the split's positive side.
    positive: bool,
}

impl<T: Decide> ArcLoop<T> {
    /// **`split_ring_path_torus_loop`** at `p`: positive on the arc's
    /// own loop, the margin charged `slack` ([`charge`]).
    fn read(&self, p: Point3<T>, slack: T, band: Band) -> Result<Sign, Indeterminate> {
        let m = self.split.margin(p);
        decide(
            "split_ring_path_torus_loop",
            Margin::of(charge(if self.positive { m } else { -m }, slack)),
            band,
        )
    }
}

impl<T: Decide> Quadric<T> {
    /// **The loop arc of a spiric oval on this torus**, over `params`;
    /// `None` for any other carrier, and on a sphere or a cone. The
    /// oval's plane, parallel to the axis, cuts the torus in it and the
    /// oval across the axis's trace: its own loop is on the carrier's
    /// `+m` side of that trace.
    pub(crate) fn torus_spiric_arc(
        &self,
        carrier: &geom::Curve3<T>,
        (t0, t1): (T, T),
    ) -> Option<LoopArc<T>> {
        let (
            Self::Torus { .. },
            &geom::Curve3::Spiric {
                center,
                axis,
                u_ref,
                major_radius,
                minor_radius,
                offset,
            },
        ) = (*self, carrier)
        else {
            return None;
        };
        Some(LoopArc::Oval(Oval {
            centre: center,
            axis,
            u_ref,
            major: major_radius,
            minor: minor_radius,
            offset,
            span: (t0.min(t1), t0.max(t1)),
            own: Some(ArcLoop {
                split: LoopSplit::Side {
                    origin: center,
                    dir: axis.cross(u_ref),
                },
                positive: true,
            }),
        }))
    }

    /// **The loop arc of a circle on this torus**, over `params`: a
    /// meridian or a parallel, with its [`ArcLoop`]; `Ok(None)` for any
    /// other circle (no plane section of a torus outside the touching
    /// poses is another circle) and on a sphere or a cone. The circle's
    /// axis is decided square to the torus's
    /// (**`split_ring_torus_meridian`**: `n̂·â`, levered at the circle's
    /// radius) or along it (**`split_ring_torus_parallel`**:
    /// `‖n̂ × â‖`, levered at the radius), and a parallel's side, its
    /// radius less `R` (**`split_ring_torus_parallel_side`**). A parallel
    /// of radius `R` in that band is the tube's top or bottom circle,
    /// whose plane touches the torus: its arc is a
    /// [`LoopArc::Crest`], told apart from the other by its centre's
    /// height (**`split_ring_torus_crest`**). None is charged a
    /// coordinate resolution: a section lane mints a circle's axis and
    /// radius from the plane's and the torus's stored directions and
    /// radii, never from a difference of far points
    /// (`far_frame_rows::a_torus_circle_the_section_lane_mints_in_the_box_reads_its_kind_at_the_origin`).
    pub(crate) fn torus_circle_arc(
        &self,
        carrier: &geom::Curve3<T>,
        params: (T, T),
        band: Band,
    ) -> Result<Option<LoopArc<T>>, Indeterminate> {
        let (
            Self::Torus {
                centre,
                axis,
                major,
                ..
            },
            geom::Curve3::Circle {
                center: k,
                axis: n,
                radius,
                ..
            },
        ) = (*self, carrier)
        else {
            return Ok(None);
        };
        let (k, n, radius) = (*k, *n, *radius);
        let Some(LoopArc::Conic(conic)) = LoopArc::of(carrier, params) else {
            return Ok(None);
        };
        let Conic {
            centre: c,
            axis: a,
            u_ref,
            a: ra,
            span,
            ..
        } = conic;
        let arc = |own| {
            LoopArc::Conic(Conic {
                own: Some(own),
                ..conic
            })
        };
        if decide(
            "split_ring_torus_meridian",
            Margin::levered(n.dot(axis), radius),
            band,
        )? == Sign::Zero
        {
            let w = k - centre;
            let w = w - axis * w.dot(axis);
            return Ok(Some(arc(ArcLoop {
                split: LoopSplit::Side {
                    origin: centre,
                    dir: w / w.norm(),
                },
                positive: true,
            })));
        }
        if decide(
            "split_ring_torus_parallel",
            Margin::levered(n.cross(axis).norm(), radius),
            band,
        )? != Sign::Zero
        {
            return Ok(None);
        }
        let positive = match decide(
            "split_ring_torus_parallel_side",
            Margin::of(radius - major),
            band,
        )? {
            Sign::Positive => true,
            Sign::Negative => false,
            Sign::Zero => {
                // The tube's top or bottom circle: its side of the
                // equator plane (**`split_ring_torus_crest`**, the
                // centre's height, `±r` on the torus).
                let top = match decide(
                    "split_ring_torus_crest",
                    Margin::of((k - centre).dot(axis)),
                    band,
                )? {
                    Sign::Positive => true,
                    Sign::Negative => false,
                    Sign::Zero => return Ok(None),
                };
                return Ok(Some(LoopArc::Crest {
                    centre: c,
                    axis: a,
                    u_ref,
                    radius: ra,
                    span,
                    core: (centre, axis, major),
                    own: ArcLoop {
                        split: LoopSplit::Side {
                            origin: centre,
                            dir: axis,
                        },
                        positive: top,
                    },
                }));
            }
        };
        Ok(Some(arc(ArcLoop {
            split: LoopSplit::Radius {
                origin: centre,
                axis,
                radius: major,
            },
            positive,
        })))
    }
}

/// **Whether `path` crosses `arcs` an odd number of times**: whether its
/// ends lie on opposite sides of the closed curve the arcs make (module
/// docs). `arrives_on` names the arc the path's end lies on, at an
/// interior point; its crossing there is the arrival and is not
/// counted. `None` when a reading of a crossing not passed over lands
/// in the zero band; `Err` when one lands in the escalation band, which
/// says nothing about the parity either: the caller asks another path.
/// A crossing is passed over when any of its in-span readings is
/// decided out of span, even where another escalates.
///
/// - A circle piece meets a conic's or an oval's plane where
///   `A cos θ + B sin θ = −D/r` (`A`, `B` the plane normal's components
///   on the piece's frame, `D` the piece's centre's offset from the
///   plane): at two parameters when `r·√(A² + B²) > |D|`
///   (**`split_ring_path_meets_plane`**, on the gap `r·√(A² + B²) − |D|`
///   in metres: moving the plane by it flips the meeting). A graze inside
///   the gap's band escalates, and the caller asks the next path. On the
///   arrival arc, the root nearer the piece's end is the arrival. A gap
///   in the zero band is a piece along the plane, which meets no conic
///   arc it is decided apart from ([`misses_in_plane`]): a path's
///   meridian or parallel through a point of an arc's carrier, or of its
///   plane's other loop, runs so.
/// - A segment meets a conic's or an oval's plane where its ends'
///   offsets from it (**`split_ring_path_segment_side`**) differ in
///   sign. A segment decided apart from a conic arc
///   ([`segment_misses`]) meets it nowhere, as a torus path's lead from
///   a point on an arc's plane is. One with an end on the plane and the
///   other decided off it meets the plane once, at that end: the
///   crossing is read as any other, its place on the segment in the zero
///   band, so it is passed over where the arc reads it out of span (a
///   path from a ring vertex on an arc's plane, off the arc) and says
///   nothing otherwise. One with both ends on the plane says nothing
///   unless its length is in the band (**`split_ring_path_lead_point`**:
///   a lead from a point already on its tube) and that point is decided
///   off the arc (on the plane's other loop, or out of the arc's span).
/// - A ruling meets a circle piece's plane once (it is decided across
///   it, **`split_ring_path_line_across`**: the cosine between the
///   plane's normal and the ruling, levered at the piece's radius), and
///   another ruling nowhere off the apex (the two are decided apart,
///   **`split_ring_path_rulings_apart`**: the sine between them,
///   levered at the segment's distance from the apex, and charged each
///   direction's rounding: the resolution over that distance and over
///   the arc's length).
/// - On a torus, a meeting point counts only on the arc's own loop of
///   its plane ([`ArcLoop`], **`split_ring_path_torus_loop`**).
/// - Every reading above is charged the [`resolution`] of the path's
///   points and the arcs' centres ([`charge`]), but the cosine across,
///   read between two directions, and two readings whose zero only hands
///   the case to charged readings, so that a charge would only widen it:
///   the lead's length, and [`misses_in_plane`]'s
///   **`split_ring_path_same_circle`**, whose zero hands the arcs' ends
///   to the in-span readings. In a frame far from the
///   origin, points that should lie on one plane or one circle are
///   stored further apart than the band, and a margin inside their
///   rounding stands down rather than decide.
/// - Each meeting point counts when it lies strictly inside the piece's
///   span and the arc's (**`split_ring_path_in_span`**: the distance
///   along the piece or the arc to a span end — a parameter levered at a
///   circle's radius, a conic's minor semi-axis or an oval's tube radius
///   (each the least speed of its parameter), or a line's length —
///   times the slope the piece crosses the other's plane at. That is the
///   carrier displacement that moves the root past the end: near a graze
///   a root moves by the displacement over the slope, so a span end a
///   decided arc length away can still be inside its reach.)
pub(crate) fn path_parity<T: Decide>(
    path: &Path<T>,
    arcs: &[LoopArc<T>],
    arrives_on: Option<usize>,
    band: Band,
) -> Result<Option<bool>, Indeterminate> {
    let decide_m = |name, margin| decide(name, margin, band);
    let slack = path_resolution(path, arcs);
    // A crossing's in-span readings are kept whole, escalations included:
    // one decided out of span passes the crossing over whatever the
    // others read.
    let in_span = |t: T, span: (T, T), arm: T| span_readings(t, span, arm, slack, band);
    let inside = Ok(Sign::Positive);
    // A crossing of a torus arc's plane on the plane's other loop is no
    // crossing of the arc: its side is one more reading of the crossing.
    let on_own =
        |own: Option<ArcLoop<T>>, x: Point3<T>| own.map_or(inside, |l| l.read(x, slack, band));
    // The arms below that read a section arc match only a conic or an
    // oval, which both have a plane and a parameter.
    let section = |arc: &LoopArc<T>| match arc.plane() {
        Some(sec) => sec,
        None => unreachable!("only a conic or an oval arc is read as a section arc"),
    };
    let param = |arc: &LoopArc<T>, x: Point3<T>| match arc.param_at(x) {
        Some(t) => t,
        None => unreachable!("only a conic or an oval arc is read as a section arc"),
    };
    let mut odd = false;
    let last = path.pieces.len().saturating_sub(1);
    for (i, piece) in path.pieces.iter().enumerate() {
        for (j, arc) in arcs.iter().enumerate() {
            let arrival = i == last && arrives_on == Some(j);
            let mut readings: Vec<[Result<Sign, Indeterminate>; 5]> = Vec::with_capacity(2);
            match (*piece, arc.clone()) {
                (Piece::Arc(p) | Piece::Meridian(p), LoopArc::Conic(_) | LoopArc::Oval(_)) => {
                    let sec = section(arc);
                    let Some(roots) =
                        plane_roots(&p, (sec.origin, sec.normal), arrival, slack, band)?
                    else {
                        if let LoopArc::Conic(conic) = arc
                            && !arrival
                            && misses_in_plane(&p, conic, slack, band)?
                        {
                            continue;
                        }
                        return Ok(None);
                    };
                    for (t, slope) in roots {
                        let [p0, p1] = in_span(t, p.span, p.radius * slope);
                        let [a0, a1] = in_span(param(arc, p.at(t)), sec.span, sec.speed * slope);
                        readings.push([p0, p1, a0, a1, on_own(sec.own, p.at(t))]);
                    }
                }
                // A crest is a torus's, whose paths' arcs are parallels
                // (`Piece::Arc`) and meridians. A parallel keeps its
                // distance from the axis, so it meets the cylinder
                // `ρ = R` nowhere unless it runs along it
                // (**`split_ring_path_crest_graze`**: its radius less `R`).
                (
                    Piece::Arc(p),
                    LoopArc::Crest {
                        core: (.., major), ..
                    },
                ) => {
                    if decide_m(
                        "split_ring_path_crest_graze",
                        Margin::of(charge(p.radius - major, slack)),
                    )? == Sign::Zero
                    {
                        return Ok(None);
                    }
                }
                // A meridian lies in a plane holding the axis, where
                // `ρ − R` is the offset from its centre on the core along
                // the radial `ê`: it crosses the cylinder `ρ = R` where it
                // crosses the plane through its centre square to `ê`, on
                // the tube's top and bottom.
                (
                    Piece::Meridian(p),
                    LoopArc::Crest {
                        centre,
                        axis,
                        u_ref,
                        radius,
                        span,
                        core: (c, a, _),
                        own,
                    },
                ) => {
                    let w = p.centre - c;
                    let e = w - a * w.dot(a);
                    let e = e / e.norm();
                    let Some(roots) = plane_roots(&p, (p.centre, e), arrival, slack, band)? else {
                        return Ok(None);
                    };
                    let v_ref = axis.cross(u_ref);
                    for (t, slope) in roots {
                        let w = p.at(t) - centre;
                        let s = branch(w.dot(v_ref).atan2(w.dot(u_ref)), span);
                        let [p0, p1] = in_span(t, p.span, p.radius * slope);
                        let [a0, a1] = in_span(s, span, radius * slope);
                        readings.push([p0, p1, a0, a1, own.read(p.at(t), slack, band)]);
                    }
                }
                // The torus's one segment is the lead along a tube radius,
                // in a meridian half-plane, where `ρ − R` is a multiple of
                // its offset from the core point at its start, so it keeps
                // its sign (**`split_ring_path_crest_side`**). A segment
                // whose ends are decided across the cylinder is no lead,
                // and says nothing.
                (
                    Piece::Segment { from, to, .. },
                    LoopArc::Crest {
                        core: (c, a, major),
                        ..
                    },
                ) => {
                    if arrival {
                        continue;
                    }
                    let rho_less = |p: Point3<T>| {
                        let w = p - c;
                        (w - a * w.dot(a)).norm() - major
                    };
                    let side = |p| {
                        decide_m(
                            "split_ring_path_crest_side",
                            Margin::of(charge(rho_less(p), slack)),
                        )
                    };
                    let (s0, s1) = (side(from)?, side(to)?);
                    if s0 == Sign::Zero || s1 == Sign::Zero || s0 != s1 {
                        return Ok(None);
                    }
                }
                (Piece::Arc(p) | Piece::Meridian(p), LoopArc::Line { origin, dir, span }) => {
                    let across = p.axis.dot(dir);
                    if decide_m(
                        "split_ring_path_line_across",
                        Margin::levered(across, p.radius),
                    )? == Sign::Zero
                    {
                        return Ok(None);
                    }
                    if arrival {
                        continue;
                    }
                    let s = p.axis.dot(p.centre - origin) / across;
                    let t = p.param(origin + dir * s);
                    // The plane moved by δ moves the root by δ over the
                    // slope the ruling crosses it at, `|m̂·d̂|`.
                    let slope = across.abs();
                    let [p0, p1] = in_span(t, p.span, p.radius * slope);
                    let [a0, a1] = in_span(s, span, slope);
                    readings.push([p0, p1, a0, a1, inside]);
                }
                (
                    Piece::Segment { from, to, .. } | Piece::Ruling { from, to },
                    LoopArc::Conic(_) | LoopArc::Oval(_),
                ) => {
                    if arrival {
                        continue;
                    }
                    let sec = section(arc);
                    let offset = |x: Point3<T>| sec.normal.dot(x - sec.origin);
                    let (d0, d1) = (offset(from), offset(to));
                    let side =
                        |d| decide_m("split_ring_path_segment_side", Margin::of(charge(d, slack)));
                    let (s0, s1) = (side(d0)?, side(d1)?);
                    // A segment decided apart from a conic arc meets it
                    // nowhere. One along the plane says nothing unless its
                    // length is in the band: the lead from a point already
                    // on the tube it moves onto, which meets the arc
                    // nowhere where that point is decided off it (on the
                    // plane's other loop, or out of the arc's span, read at
                    // the arc's least speed).
                    if (s0 == Sign::Zero || s1 == Sign::Zero)
                        && let LoopArc::Conic(conic) = arc
                        && segment_misses((from, to), conic, slack, band)?
                    {
                        continue;
                    }
                    if s0 == Sign::Zero && s1 == Sign::Zero {
                        let point =
                            decide_m("split_ring_path_lead_point", Margin::of((to - from).norm()))?
                                == Sign::Zero;
                        if !point {
                            return Ok(None);
                        }
                        let [a0, a1] = in_span(param(arc, from), sec.span, sec.speed);
                        let reading = [a0, a1, on_own(sec.own, from)];
                        if reading.contains(&Ok(Sign::Negative)) {
                            continue;
                        }
                        if let Some(&Err(diag)) = reading.iter().find(|r| r.is_err()) {
                            return Err(diag);
                        }
                        return Ok(None);
                    }
                    if s0 == s1 {
                        continue;
                    }
                    let x = from + (to - from) * (d0 / (d0 - d1));
                    // The plane moved by δ moves the root by δ over the
                    // slope the segment crosses it at, `|n̂·d̂|`.
                    let slope = ((d0 - d1) / (to - from).norm()).abs();
                    let [a0, a1] = in_span(param(arc, x), sec.span, sec.speed * slope);
                    // With one end on the plane and the other decided off
                    // it, the segment meets the plane once, at that end:
                    // the crossing's place on the segment is in the zero
                    // band, so it is passed over where the arc reads it
                    // out of span or on the plane's other loop, and says
                    // nothing otherwise.
                    let on_end = if s0 == Sign::Zero || s1 == Sign::Zero {
                        Ok(Sign::Zero)
                    } else {
                        inside
                    };
                    readings.push([on_end, inside, a0, a1, on_own(sec.own, x)]);
                }
                (Piece::Segment { ruling, lever, .. }, LoopArc::Line { dir, span, .. }) => {
                    if arrival {
                        continue;
                    }
                    // Each direction's sine carries its ends' rounding
                    // over their distance: the ruling's over the lever,
                    // the arc's over its length.
                    let rounding = slack / lever + slack / (span.1 - span.0);
                    if decide_m(
                        "split_ring_path_rulings_apart",
                        Margin::levered(charge(ruling.cross(dir).norm(), rounding), lever),
                    )? != Sign::Positive
                    {
                        return Ok(None);
                    }
                }
                // Two rulings of a cylinder are parallel, and meet nowhere
                // where they are decided apart
                // (**`split_ring_path_rulings_distinct`**: the distance
                // between their lines, charged `slack`).
                (Piece::Ruling { from, .. }, LoopArc::Line { origin, dir, .. }) => {
                    if arrival {
                        continue;
                    }
                    let gap = (from - origin).cross(dir).norm() / dir.norm();
                    if decide_m(
                        "split_ring_path_rulings_distinct",
                        Margin::of(charge(gap, slack)),
                    )? != Sign::Positive
                    {
                        return Ok(None);
                    }
                }
                // A crest is a torus's, whose paths hold no cylinder ruling.
                (Piece::Ruling { .. }, LoopArc::Crest { .. }) => return Ok(None),
                // A spline arc meets a piece where the curve-pair table
                // says ([`spline_crossings`]).
                (piece, LoopArc::Spline(arc)) => {
                    match spline_crossings(&piece, &arc, arrival, slack, band)? {
                        Some(n) => {
                            if n % 2 == 1 {
                                odd = !odd;
                            }
                        }
                        None => return Ok(None),
                    }
                }
            }
            for reading in readings {
                if reading.contains(&Ok(Sign::Negative)) {
                    continue;
                }
                if let Some(&Err(diag)) = reading.iter().find(|r| r.is_err()) {
                    return Err(diag);
                }
                if reading.contains(&Ok(Sign::Zero)) {
                    return Ok(None);
                }
                odd = !odd;
            }
        }
    }
    Ok(Some(odd))
}

/// **How many times `piece` crosses the spline arc `arc`**, read through
/// the curve-pair table ([`geom_brep::curve_pair::meet`]), which the
/// arc's evidence of lying on the surface makes a reading of crossings
/// on it ([`SplineArc`]):
/// every meeting it finds lies inside both spans and is a crossing, the
/// sine between the two curves' directions there decided past the band
/// (**`split_ring_path_spline_across`**, levered at the piece's length
/// and charged `slack`). The arrival on the closing chord, at the end of
/// the path's last piece, is no crossing before it (`arrival`). `None`
/// where the path says nothing: a meeting at either span's end (the
/// path starts on the arc or runs through its end) or in the zero band
/// of the crossing reading, a shared run, or a meeting the reader could
/// not settle ([`meet_refused`]). An escalation of the reader or of a
/// crossing escalates.
fn spline_crossings<T: Decide>(
    piece: &Piece<T>,
    SplineArc { carrier, span }: &SplineArc<T>,
    arrival: bool,
    slack: T,
    band: Band,
) -> Result<Option<usize>, Indeterminate> {
    use geom_brep::curve_pair::{Hit, Span, SpanEnd, meet};
    let (curve, params, length) = match *piece {
        Piece::Arc(p) | Piece::Meridian(p) => (
            geom::Curve3::Circle {
                center: p.centre,
                axis: p.axis,
                radius: p.radius,
                u_ref: p.u_ref,
            },
            p.span,
            p.radius * (p.span.1 - p.span.0),
        ),
        Piece::Segment { from, to, .. } | Piece::Ruling { from, to } => (
            geom::Curve3::Line {
                origin: from,
                dir: to - from,
            },
            (T::zero(), T::one()),
            (to - from).norm(),
        ),
    };
    // A piece of no length (a ruled path's first, from an end already on
    // the turn's height or parallel) crosses nothing: the next piece
    // starts at its point and reads a meeting there as its own start
    // (**`split_ring_path_spline_piece`**, its length).
    if decide(
        "split_ring_path_spline_piece",
        Margin::of(charge(length, slack)),
        band,
    )? == Sign::Zero
    {
        return Ok(Some(0));
    }
    let on_piece = Span::new(&curve, params);
    let on_arc = Span::new(carrier, *span);
    let met = match meet(&on_piece, &on_arc, band) {
        Ok(met) => met,
        Err(refusal) => return meet_refused(refusal.fault),
    };
    if met.shared.is_some() {
        return Ok(None);
    }
    let mut crossings = 0;
    for m in met.points {
        let (tp, ta) = match (m.on_a, m.on_b) {
            (Hit::End(SpanEnd::Stop), Hit::On { .. }) if arrival => continue,
            (Hit::On { t: tp, .. }, Hit::On { t: ta, .. }) => (tp, ta),
            _ => return Ok(None),
        };
        let (dp, da) = (curve.deriv(tp), carrier.deriv(ta));
        let sine = dp.cross(da).norm() / (dp.norm() * da.norm());
        if decide(
            "split_ring_path_spline_across",
            Margin::levered(charge(sine, slack / length), length),
            band,
        )? != Sign::Positive
        {
            return Ok(None);
        }
        crossings += 1;
    }
    Ok(Some(crossings))
}

/// **What a refused meeting of a piece and a spline arc says of the
/// path.** A meeting in band on the path is the path's, which says
/// nothing there, as a probe ray grazes; so does a limit of the reader
/// or a pose it has no closed form for. An escalation escalates. A
/// carrier of a kind its arm does not read, or two readings that
/// contradict, is the kernel's fault: a piece is a circle or a line and
/// the arc a spline, which the table reads, and a contradiction is ruled
/// out by the readings' definitions.
fn meet_refused(fault: geom_brep::curve_pair::MeetFault) -> Result<Option<usize>, Indeterminate> {
    use geom_brep::curve_pair::MeetFault;
    match fault {
        MeetFault::Escalated(diag) => Err(diag),
        MeetFault::Touch(_) | MeetFault::Unsettled(_) | MeetFault::Unsupported { .. } => Ok(None),
        MeetFault::Desync => {
            unreachable!("the meeting of a path's piece and a spline arc misread a carrier's kind")
        }
        MeetFault::Contradiction { readings } => {
            unreachable!(
                "the meeting of a path's piece and a spline arc contradicts itself: {readings}"
            )
        }
    }
}

impl<T: Decide> Conic<T> {
    fn v_ref(&self) -> Vec3<T> {
        self.axis.cross(self.u_ref)
    }

    /// The arc's point at its parameter `s`.
    fn at(&self, s: T) -> Point3<T> {
        let (sn, cs) = s.sin_cos();
        self.centre + self.u_ref * (self.a * cs) + self.v_ref() * (self.b * sn)
    }

    /// The parameter of `x`, a point of the conic's plane, on the span's
    /// branch: its eccentric anomaly.
    fn param(&self, x: Point3<T>) -> T {
        let w = x - self.centre;
        branch(
            (w.dot(self.v_ref()) / self.b).atan2(w.dot(self.u_ref) / self.a),
            self.span,
        )
    }

    /// A lower bound on the distance from `x` to the arc: the distance
    /// to the arc of the circle of radius `b` over the same span, less
    /// `|a − b|`, which bounds how far a conic point lies from the
    /// circle's at the same parameter. The circle arc's nearest point is
    /// at `x`'s direction clamped to the span: on the span's branch the
    /// end on `x`'s side is the nearer.
    pub(crate) fn distance_floor(&self, x: Point3<T>) -> T {
        let w = x - self.centre;
        let s = branch(w.dot(self.v_ref()).atan2(w.dot(self.u_ref)), self.span);
        let s = s.max(self.span.0).min(self.span.1);
        let (sn, cs) = s.sin_cos();
        let nearest = self.centre + (self.u_ref * cs + self.v_ref() * sn) * self.b;
        (x - nearest).norm() - (self.a - self.b).abs()
    }
}

/// **Whether `t` lies inside `span`**, read at each end
/// (**`split_ring_path_in_span`**: the parameter's distance from the
/// end, levered at `arm`, charged `slack` metres: `slack / arm` in the
/// parameter, [`charge`]), each reading kept whole, escalations
/// included.
fn span_readings<T: Decide>(
    t: T,
    (lo, hi): (T, T),
    arm: T,
    slack: T,
    band: Band,
) -> [Result<Sign, Indeterminate>; 2] {
    let read = |m: T| {
        decide(
            "split_ring_path_in_span",
            Margin::levered(charge(m, slack / arm), arm),
            band,
        )
    };
    [read(t - lo), read(hi - t)]
}

/// **`m` shrunk toward zero by `slack`**, to zero inside it: a margin
/// charged with the rounding it may carry, so that its sign is decided
/// only past that rounding.
fn charge<T: Real>(m: T, slack: T) -> T {
    (m - slack).max(T::zero()) + (m + slack).min(T::zero())
}

/// **How far apart points stored at `points`' distances from the
/// origin may lie where they should coincide**: `4ε` times the farthest
/// distance `far`. A rounding to the grid moves a coordinate of a point
/// within `far` of the origin by at most half an ulp, `ε·far/2`. Each of
/// two points that should coincide is rounded at most twice: when it is
/// stored, and in the one step that places it from stored points (a
/// centre moved along an axis, a point placed round a circle, a lead's
/// end moved along a tube radius). So they part by at most `2ε·far` in
/// each coordinate, and by at most `2√3·ε·far` as a vector, which
/// `4ε·far` bounds. A margin's own arithmetic adds nothing at that
/// scale: its subtraction of stored coordinates rounds relative to
/// their difference, and the rest relative to the margin. A reading
/// between such points charges the resolution to its margin, so that
/// where coordinates cannot resolve the band it stands down rather than
/// deciding on their rounding.
fn resolution<T: Real>(points: &[Point3<T>]) -> T {
    let far = points
        .iter()
        .fold(T::zero(), |m, &x| m.max((x - Point3::origin()).norm()));
    far * T::from_f64(4.0 * f64::EPSILON)
}

/// **The [`resolution`] of a reading between `path` and `arcs`**: of
/// every piece's ends and centre and every arc's centre.
fn path_resolution<T: Decide>(path: &Path<T>, arcs: &[LoopArc<T>]) -> T {
    let mut points = Vec::with_capacity(3 * path.pieces.len() + arcs.len());
    for piece in &path.pieces {
        match *piece {
            Piece::Arc(p) | Piece::Meridian(p) => {
                points.extend([p.centre, p.at(p.span.0), p.at(p.span.1)]);
            }
            Piece::Segment { from, to, .. } | Piece::Ruling { from, to } => {
                points.extend([from, to]);
            }
        }
    }
    for arc in arcs {
        match arc {
            LoopArc::Conic(Conic { centre, .. })
            | LoopArc::Oval(Oval { centre, .. })
            | LoopArc::Crest { centre, .. } => points.push(*centre),
            LoopArc::Line { origin, .. } => points.push(*origin),
            LoopArc::Spline(SplineArc { carrier, span }) => {
                points.extend([carrier.eval(span.0), carrier.eval(span.1)]);
            }
        }
    }
    resolution(&points)
}

/// **Whether the segment `from → to`, an end of which lies on
/// `conic`'s plane, misses the arc**
/// (**`split_ring_path_segment_apart`**): its midpoint is decided
/// farther from the arc ([`Conic::distance_floor`]) than half its
/// length, within which every point of it lies of the midpoint,
/// charged `slack` ([`charge`]).
fn segment_misses<T: Decide>(
    (from, to): (Point3<T>, Point3<T>),
    conic: &Conic<T>,
    slack: T,
    band: Band,
) -> Result<bool, Indeterminate> {
    let half = (to - from).norm() * T::from_f64(0.5);
    let mid = from + (to - from) * T::from_f64(0.5);
    Ok(decide(
        "split_ring_path_segment_apart",
        Margin::of(charge(conic.distance_floor(mid) - half, slack)),
        band,
    )? == Sign::Positive)
}

/// **Whether the circle piece `p`, which [`plane_roots`] cannot cut
/// with `conic`'s plane, misses the arc**: it runs along that plane,
/// as a path's meridian or parallel through a point of an arc's
/// carrier, or of its plane's other loop, does. Either:
/// - the two circles are decided apart
///   (**`split_ring_path_coplanar_apart`**: the annulus about the
///   conic's centre between `min(a, b)` and `max(a, b)`, which holds
///   the conic, against the piece's circle, by the centres' distance).
///   A point on both would bound that distance by the triangle
///   inequality, so the reading holds whatever the planes: a parallel
///   against its plane's other loop on a torus, a meridian against the
///   one across the axis; or
/// - they are one circle (**`split_ring_path_same_circle`**: the larger
///   of the centres' distance and each radius's difference; with
///   [`plane_roots`]' gap in the band, the planes then lie within the
///   band of each other too) and the arcs are decided disjoint on it:
///   each end of either lies outside the other's span
///   ([`span_readings`]). Two arcs of one circle overlap only where one
///   holds an end of the other.
///
/// `Ok(false)` where neither is decided. The apart and in-span readings
/// are charged `slack` ([`charge`]).
fn misses_in_plane<T: Decide>(
    p: &CircleArc<T>,
    conic: &Conic<T>,
    slack: T,
    band: Band,
) -> Result<bool, Indeterminate> {
    let apart = (p.centre - conic.centre).norm();
    let (inner, outer) = (conic.a.min(conic.b), conic.a.max(conic.b));
    let gap = (apart - p.radius - outer)
        .max(inner - p.radius - apart)
        .max(p.radius - outer - apart);
    if decide(
        "split_ring_path_coplanar_apart",
        Margin::of(charge(gap, slack)),
        band,
    )? == Sign::Positive
    {
        return Ok(true);
    }
    let differ = apart
        .max((p.radius - conic.a).abs())
        .max((p.radius - conic.b).abs());
    if decide("split_ring_path_same_circle", Margin::of(differ), band)? != Sign::Zero {
        return Ok(false);
    }
    // An end lies outside a span when either of its two readings is
    // decided outside; an escalation counts only where neither is.
    let outside = |t: T, span: (T, T), arm: T| -> Result<bool, Indeterminate> {
        let readings = span_readings(t, span, arm, slack, band);
        if readings.contains(&Ok(Sign::Negative)) {
            return Ok(true);
        }
        readings.iter().find_map(|r| r.err()).map_or(Ok(false), Err)
    };
    // Two overlapping arcs of one circle hold at least two ends inside
    // each other, so any three of the four readings decide the same.
    for t in [p.span.0, p.span.1] {
        if !outside(conic.param(p.at(t)), conic.span, conic.b)? {
            return Ok(false);
        }
    }
    for s in [conic.span.0, conic.span.1] {
        if !outside(p.param(conic.at(s)), p.span, p.radius)? {
            return Ok(false);
        }
    }
    Ok(true)
}

/// **Where the circle piece `p` meets the plane through `o` with unit
/// normal `n`**: the parameters to read, each with the slope `|n̂·τ̂|`
/// the piece crosses the plane at. `A cos θ + B sin θ = −D/r` (`A`, `B`
/// the normal's components on the piece's frame, `D` the piece's
/// centre's offset from the plane) holds at two parameters when
/// `r·√(A² + B²) > |D|` (**`split_ring_path_meets_plane`**, on the gap
/// `r·√(A² + B²) − |D|` in metres: moving the plane by it flips the
/// meeting, charged `slack`, [`charge`]); none when it is decided short,
/// and `None` when it grazes in the band. On the arrival arc
/// (`arrival`), the root nearer the piece's end is the arrival and only
/// the other is read.
fn plane_roots<T: Decide>(
    p: &CircleArc<T>,
    (o, n): (Point3<T>, Vec3<T>),
    arrival: bool,
    slack: T,
    band: Band,
) -> Result<Option<Vec<(T, T)>>, Indeterminate> {
    let (ca, cb) = (n.dot(p.u_ref), n.dot(p.v_ref()));
    let d = n.dot(p.centre - o);
    let rho = (ca.powi(2) + cb.powi(2)).sqrt();
    // The gap `rρ − |D|`: moving the plane by it flips the meeting, so
    // it is the deviation the sign rests on.
    match decide(
        "split_ring_path_meets_plane",
        Margin::of(charge(p.radius * rho - d.abs(), slack)),
        band,
    )? {
        Sign::Negative => return Ok(Some(Vec::new())),
        Sign::Zero => return Ok(None),
        Sign::Positive => {}
    }
    let phase = cb.atan2(ca);
    let offset = (-d / (p.radius * rho)).max(-T::one()).min(T::one()).acos();
    let [r0, r1] = [phase + offset, phase - offset].map(|t| branch(t, p.span));
    // On the arrival arc, the root nearer the end is the arrival; the
    // other is read. The pick is a raw comparison and needs no decision.
    // The arrival lies on the plane up to rounding δ, and a root
    // misplaced by δ in the plane's offset moves by δ over the slope it
    // crosses at (as the in-span readings are levered): near a graze,
    // with half-angle ω between the roots, the slope is `ρ·sin ω` and the
    // roots lie `2rω` apart along the arc, so the root error against
    // their separation is `δ/(2rρ·sin ω·ω) ≈ δ/(4g)` for the gap
    // `g = rρ − |D| ≈ rρω²/2`. The pick holds while that is under a half.
    // The gap is charged the coordinates' resolution `s`, so a decided
    // gap is `g > Kε + s`, and the rounding is `δ ≤ ε + s`: the ratio is
    // under a quarter wherever the frame lies, and at most `1/(4K)` where
    // the coordinates resolve the band (`s ≪ ε`). The bound is the guard.
    let roots = if arrival {
        let nearer = (r0 - p.span.1).abs() - (r1 - p.span.1).abs();
        vec![nearer.select_le_zero(r1, r0)]
    } else {
        vec![r0, r1]
    };
    // A carrier moved by δ moves the root by δ over the slope the piece
    // crosses the plane at, `|n̂·τ̂|`: each in-span reading is levered by
    // it, so its margin is the displacement that moves the root past the
    // span's end.
    Ok(Some(
        roots
            .into_iter()
            .map(|t| {
                let (st, ct) = t.sin_cos();
                (t, (cb * ct - ca * st).abs())
            })
            .collect(),
    ))
}

