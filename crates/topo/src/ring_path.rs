//! **A ring lane's chart-free reading on a cylinder, a sphere, a cone
//! or a torus face**: the parity of a path on the face's surface across
//! a closed curve of loop arcs, which says whether the path's ends lie
//! on one side of the curve or on opposite sides. A spline wall is read
//! the same way along its chart's iso curves ([`SplineWall`]).
//!
//! The path is made of pieces whose meeting with a loop arc is closed
//! form: on a cylinder or a cone, a segment of a ruling and an arc of a
//! parallel (the circle at one height), in either order, on a cone on
//! the ends' nappe and never through the apex; on a sphere, the short
//! great-circle arc between its ends; on a torus, an arc of a meridian
//! (the tube's circle at one azimuth) and an arc of a parallel, in
//! either order, after a segment that moves the start onto the tube
//! through the end, so the pieces meet exactly. On a cylinder or a cone
//! a detour is two such ruled paths composed at a turn, a point of the
//! end's parallel or ruling at a guide point's azimuth or height
//! ([`Carrier::detours`]): its pieces are the same kinds, so they meet
//! a loop arc in the same closed forms. A loop arc is a plane
//! section of the surface (a circle or an ellipse: no lane mints another
//! conic; on a torus, also a spiric oval), a ruling of a cylinder or a
//! cone, or a spline. So a piece meets a section arc only where it
//! crosses the arc's plane, which a circle piece does at most twice and
//! a segment once, and it meets a ruling only where the ruling crosses a
//! parallel's plane. Two rulings of a cone meet only at the apex, which
//! no piece reaches, and two of a cylinder nowhere unless they are one.
//! A piece meets a spline arc where the curve-pair table finds them
//! meeting ([`geom_brep::curve_pair::meet`]), each meeting decided a
//! crossing inside both spans.
//!
//! A plane cuts a torus in up to two loops, so on a torus a crossing of
//! an arc's plane lies on the arc's own loop only on that loop's side
//! of the split between the two ([`ArcLoop`]): a loop arc on a torus is
//! a meridian, a parallel or a spiric oval, whose plane's other loop is
//! the meridian across the axis, the parallel across the tube or the
//! oval across the axis's trace. The split
//! is decided at the crossing, **`split_ring_path_torus_loop`**, as the
//! boolean join's section loops are told apart.
//!
//! The tube's top and bottom circles (the parallels of radius `R`) are
//! the exception: their plane touches the torus along them, so a path
//! meets it only on the circle and never crosses it. They are read
//! across the cylinder `ρ = R` about the axis instead, which cuts the
//! torus transversally in exactly those two circles, told apart by their
//! height along the axis ([`LoopArc::Crest`]). A parallel piece keeps its
//! distance from the axis and a meridian piece crosses that cylinder at
//! the top and the bottom of the tube, through the plane through its
//! centre square to its radial, so each crossing is closed form too.
//!
//! The parity does not depend on the path where the curve is
//! null-homotopic where the paths run. Every closed curve on a sphere
//! is. A cylinder needs no such premise: it is an annulus, on which any
//! two closed curves cross an even number of times (the mod-2
//! intersection form of its first homology, generated by the circle
//! round the axis, is zero, since that circle is pushed off itself along
//! the axis), so two paths with the same ends cross any closed curve
//! alike; and an embedded closed curve on it, winding round the axis
//! (a drum wall's section loop, which goes all the way round) or not,
//! separates it. Which side of it is the region a curve bounds is the
//! curve's to say only where it does not wind: there it bounds a disc.
//! So a parity read as membership of a cylinder face's region (the ring
//! re-homing's) rests on the face being a disc of the chart, no loop of
//! it winding round the axis, as on a cone and a torus; a run that
//! winds (a seamless band's) bounds no disc, and its side would be read
//! off its orientation, which the parity does not see. On a cone, the paths run on the punctured nappe, an annulus, and
//! the curve bounds a disc of it: it lies on one face, and no loop of the
//! face winds round the axis, so no curve on it winds round the apex. On
//! a torus, the paths run anywhere on it and the curve bounds a disc: it
//! lies on one face, no loop of which winds round either period, so the
//! face lifts to a disc of the chart plane and a closed curve on it
//! lifts closed. A loop that does not wind is one whose chart walk closes
//! on its start, its deck elements composed to the identity
//! (`pcurves::loop_windings`' `zero`); nothing about how far the loop
//! spans the chart enters, and the at-rest pass does not yet refuse a
//! loop that winds (`work/pcert/a-seamless-band-mints-and-passes-tier-3-though-loopwraps-says-no-constructor-makes-one.md`). The parity of a path
//! across a curve that bounds is its ends' sides of the disc, whichever
//! way round the tube or the axis it goes.
//!
//! Each decision is a named trilean metered in metres. The raw picks
//! that remain — the nearer root on the arrival arc, a parameter's
//! branch, the way round a parallel — are choices every outcome of which
//! is sound, each argued at its site. A crossing is
//! passed over once any reading is decided against it, whatever its
//! other readings say: a decided rejection is decided. A reading of a
//! crossing not passed over that lands in the zero band — the path
//! grazes an arc, runs through an arc's end, or starts on an arc's
//! plane — makes the path undecided, one in the escalation band makes
//! it escalate, and the caller asks another.

use geom::Conic;
use geom_brep::ladder::{Answering, Climb, Rung, climb};
use geom_core::UnitVec3;
use geom_core::{Band, Decide, Indeterminate, InfSpeed, Lever, Margin, Point3, Real, Sign, Vec3};

use crate::validate::decide;

/// The surface a path runs on: the kinds the ring lane reads without a
/// chart.
#[derive(Clone, Copy)]
pub(crate) enum Quadric<T: Real> {
    Cylinder {
        axis: geom::Line<T>,
        radius: T,
    },
    Sphere {
        centre: Point3<T>,
        radius: T,
        /// The sphere's curvature arm, read off the surface.
        arm: Lever<T>,
    },
    /// `axis` from the apex.
    Cone {
        axis: geom::Line<T>,
        half_angle: T,
    },
    /// `axis` from the centre.
    Torus {
        axis: geom::Line<T>,
        major: T,
    },
}

impl<T: Decide> Quadric<T> {
    /// The quadric of `surface`; `None` for any other kind.
    pub(crate) fn of(surface: &geom::Surface<T>) -> Option<Self> {
        match *surface {
            geom::Surface::Cylinder { radius, .. } => Some(Self::Cylinder {
                axis: surface.axis_line()?,
                radius,
            }),
            geom::Surface::Sphere { frame, radius, .. } => {
                let center = frame.origin();
                Some(Self::Sphere {
                    centre: center,
                    radius,
                    arm: geom_brep::uniform_curvature_arm(surface),
                })
            }
            geom::Surface::Cone { half_angle, .. } => Some(Self::Cone {
                axis: surface.axis_line()?,
                half_angle,
            }),
            geom::Surface::Torus { major_radius, .. } => Some(Self::Torus {
                axis: surface.axis_line()?,
                major: major_radius,
            }),
            _ => None,
        }
    }

    /// The length a dimensionless reading at `p` on `surface`, the
    /// surface this quadric is of, is levered by: the cylinder's or the
    /// sphere's radius, the radius of the cone's parallel through `p`,
    /// or the torus's tube radius or its parallel's through `p`,
    /// whichever is smaller.
    pub(crate) fn lever(&self, surface: &geom::Surface<T>, p: Point3<T>) -> Lever<T> {
        let arm = geom_brep::curvature_lever_arm(surface, p);
        match self {
            Self::Cylinder { .. } | Self::Sphere { .. } | Self::Cone { .. } => arm,
            Self::Torus { .. } => arm.min(geom_brep::parallel_curvature_arm(surface, p)),
        }
    }

    /// The chart normal at `p` (the outward one for a face of sense
    /// `true`): the cylinder's or the sphere's radial direction, or the cone's
    /// `ŵ·cos α − â·sin α·sgn h`, `ŵ` the radial direction. `p` is off a
    /// cone's apex ([`Self::off_apex`]); on a torus, the direction from
    /// the core circle's nearest point, off the axis and the core.
    fn chart_normal(&self, p: Point3<T>) -> Vec3<T> {
        match *self {
            Self::Cylinder { axis, radius } => axis.offset(p) / radius,
            Self::Sphere { centre, radius, .. } => (p - centre) / radius,
            Self::Cone {
                axis: line @ geom::Line { dir: axis, .. },
                half_angle,
            } => {
                let (h, w) = line.param_and_offset(p);
                let (s, c) = half_angle.sin_cos();
                w.normalize() * c - axis.get() * h.select_le_zero(-s, s)
            }
            Self::Torus { axis, major, .. } => {
                let tube = p - Self::core(axis, major, p);
                tube.normalize()
            }
        }
    }

    /// The core circle's point at `p`'s azimuth, `p` off the axis.
    fn core(axis: geom::Line<T>, major: T, p: Point3<T>) -> Point3<T> {
        let w = axis.offset(p);
        axis.origin + w.normalize() * major
    }

    /// The outward normal at `p` of a face of sense `sense`
    /// ([`Self::chart_normal`] folded by the sense).
    pub(crate) fn outward(&self, p: Point3<T>, sense: bool) -> Vec3<T> {
        geom_brep::OutwardNormal::from_chart(self.chart_normal(p), sense).vec()
    }

    /// Whether `p` is decided off a cone's apex or a torus's axis (its
    /// distance from the axis, **`split_ring_path_off_apex`**, charged
    /// the two points' [`resolution`]): always on a cylinder and a
    /// sphere.
    pub(crate) fn off_apex(&self, p: Point3<T>, band: Band) -> Result<bool, Indeterminate> {
        match *self {
            Self::Cylinder { .. } | Self::Sphere { .. } => Ok(true),
            Self::Cone { axis, .. } | Self::Torus { axis, .. } => Ok(decide(
                "split_ring_path_off_apex",
                Margin::of(charge(axis.distance(p), resolution(&[axis.origin, p]))),
                band,
            )? == Sign::Positive),
        }
    }

    /// **The paths from `from` to `to`** this quadric reads, in the order
    /// they are asked; none where no path is decided to exist. Each
    /// reading below is charged the [`resolution`] of the ends and the
    /// quadric's centre or apex ([`charge`]).
    ///
    /// - A cylinder's are its two ruled paths ([`Self::ruled_paths`]).
    /// - A sphere's is the short great-circle arc, which exists when the
    ///   ends are decided neither equal nor antipodal
    ///   (**`split_ring_path_span`**: the sine between them, levered at
    ///   the radius).
    /// - A cone's are its two ruled paths ([`Self::ruled_paths`]), on the
    ///   ends' one nappe (each end's height along the axis decided
    ///   nonzero and of one sign, **`split_ring_path_nappe`**) and off
    ///   the apex. The arrival across the closing arc's section is
    ///   transversal on one of them wherever it is on either.
    /// - A torus's are two, from ends decided off the axis and off the
    ///   core circle (**`split_ring_path_off_core`**: the distance from
    ///   it). Each first moves `from` along its tube radius onto the
    ///   tube through `to` (a segment, as short as the ends' offsets off
    ///   the carrier), then runs round that tube's meridian through the
    ///   start to `to`'s parallel and round it, arriving along the
    ///   parallel; or round the start's parallel to `to`'s meridian and
    ///   round it, arriving along the meridian. A meridian loop arc
    ///   holds the first's arrival transversal and a parallel the
    ///   second's.
    pub(crate) fn paths(
        &self,
        (from, to): (Point3<T>, Point3<T>),
        band: Band,
    ) -> Result<Vec<Path<T>>, Indeterminate> {
        match *self {
            Self::Cylinder { axis, .. } => {
                self.ruled_paths(axis, (from, to), resolution(&[from, to, axis.origin]), band)
            }
            Self::Sphere {
                centre,
                radius,
                arm,
            } => {
                let slack = resolution(&[from, to, centre]);
                let a = (from - centre) / radius;
                let b = (to - centre) / radius;
                let m = a.cross(b);
                let (axis, sine) = m.direction_and_length();
                if decide(
                    "split_ring_path_span",
                    Margin::levered(charge(sine, slack / radius), arm),
                    band,
                )? != Sign::Positive
                {
                    return Ok(Vec::new());
                }
                let arc = CircleArc {
                    circle: geom::Circle::new(great_circle(centre, axis, a), radius),
                    span: (T::zero(), sine.atan2(a.dot(b))),
                };
                Ok(vec![Path {
                    pieces: vec![Piece::Arc(arc)],
                    arrival: axis.cross(b),
                    reach: None,
                }])
            }
            Self::Cone { axis, .. } => {
                if !self.off_apex(from, band)? || !self.off_apex(to, band)? {
                    return Ok(Vec::new());
                }
                let slack = resolution(&[from, to, axis.origin]);
                let nappe = |p| {
                    decide(
                        "split_ring_path_nappe",
                        Margin::of(charge(axis.param(p), slack)),
                        band,
                    )
                };
                let side = nappe(from)?;
                if side == Sign::Zero || nappe(to)? != side {
                    return Ok(Vec::new());
                }
                self.ruled_paths(axis, (from, to), slack, band)
            }
            Self::Torus {
                axis:
                    line @ geom::Line {
                        origin: centre,
                        dir: axis,
                    },
                major,
                ..
            } => {
                if !self.off_apex(from, band)? || !self.off_apex(to, band)? {
                    return Ok(Vec::new());
                }
                let core = |p| Self::core(line, major, p);
                let (kf, kt) = (core(from), core(to));
                let (off_f, off_t) = ((from - kf).norm(), (to - kt).norm());
                let slack = resolution(&[from, to, centre]);
                for off in [off_f, off_t] {
                    if decide(
                        "split_ring_path_off_core",
                        Margin::of(charge(off, slack)),
                        band,
                    )? != Sign::Positive
                    {
                        return Ok(Vec::new());
                    }
                }
                // Every piece lies on the tube of radius `off_t` about the
                // core, through `to`: `from` is moved onto it first, along
                // its own tube radius, so each turn is placed on the circle
                // the next piece runs round and the pieces meet exactly,
                // as the cone's do.
                let start = kf + (from - kf) * (off_t / off_f);
                // The ruling and lever are read only against a `Line` loop
                // arc, and no loop arc on a torus is one
                // ([`Self::torus_circle_arc`] yields conics and crests).
                let lead = Piece::Segment {
                    from,
                    to: start,
                    ruling: Vec3::zero(),
                    // Unsourced lever: the lead piece runs along no ruling, so it has no arm;
                    // zero reads its every sine Zero.
                    lever: Lever::unsourced(T::zero()),
                };
                let radial = |k: Point3<T>| (k - centre) / major;
                let (ef, et) = (radial(kf), radial(kt));
                let (hs, ws) = line.param_and_offset(start);
                let (ht, wt) = line.param_and_offset(to);
                let (rs, rt) = (ws.norm(), wt.norm());
                let mut paths = Vec::with_capacity(2);
                // Round the start's meridian to `to`'s parallel, then round.
                let turned = centre + axis.get() * ht + ef * rt;
                let meridian = parallel((kf, ef.cross(axis.get())), off_t, start, turned);
                let round = parallel((centre + axis.get() * ht, axis.get()), rt, turned, to);
                paths.push(Path {
                    pieces: vec![lead.clone(), Piece::Meridian(meridian), Piece::Arc(round)],
                    arrival: round.tangent(round.span.1),
                    reach: None,
                });
                // Round the start's parallel to `to`'s meridian, then round.
                let turned = centre + axis.get() * hs + et * rs;
                let round = parallel((centre + axis.get() * hs, axis.get()), rs, start, turned);
                let meridian = parallel((kt, et.cross(axis.get())), off_t, turned, to);
                paths.push(Path {
                    pieces: vec![lead, Piece::Arc(round), Piece::Meridian(meridian)],
                    arrival: meridian.tangent(meridian.span.1),
                    reach: None,
                });
                Ok(paths)
            }
        }
    }
}

impl<T: Decide> Quadric<T> {
    /// **The two paths of a ruled quadric**, a cylinder or a cone, from
    /// `from` to `to`, with `base` its origin or apex and `axis` its
    /// axis, each reading charged `slack`:
    ///
    /// - along `from`'s ruling to `to`'s height and round that parallel,
    ///   arriving along the parallel, where the parallel's arc is decided
    ///   of some length (**`split_ring_path_turn`**: the arc's length);
    /// - round `from`'s parallel to `to`'s ruling and along it, arriving
    ///   along the ruling, where the length along `to`'s ruling from the
    ///   turn to `to` is decided nonzero (**`split_ring_path_rise`**:
    ///   the height difference on a cylinder, the slant difference on a
    ///   cone).
    ///
    /// A path is asked only where the piece it arrives along has a length,
    /// so its arrival is a direction it travels; its first piece may have
    /// none, and is kept so the pieces meet exactly. Each turn is placed on the parallel the next
    /// piece runs round, at that parallel's own radius, so the pieces meet
    /// exactly: the ends lie on the carrier only up to the band, and a
    /// turn at the carrier's ratio would leave a gap of that offset at
    /// the seam, where a crossing could go uncounted. A ruling piece then
    /// leans off its ruling by the same offset: its crossings of a
    /// section are read from its ends, and the rulings-apart readings are
    /// decided past the band that offset lies in.
    fn ruled_paths(
        &self,
        line @ geom::Line {
            origin: base,
            dir: axis,
        }: geom::Line<T>,
        (from, to): (Point3<T>, Point3<T>),
        slack: T,
        band: Band,
    ) -> Result<Vec<Path<T>>, Indeterminate> {
        let (hf, wf) = line.param_and_offset(from);
        let (ht, wt) = line.param_and_offset(to);
        let (rf, rt) = (wf.norm(), wt.norm());
        let [turned, below] = ruled_corners(line, (from, to));
        // The length along `to`'s ruling from the turn to `to`, and that
        // ruling's unit direction, along which the second path arrives.
        let (rise, ruling_at_to) = match *self {
            Self::Cone { .. } => {
                let e = to - base;
                (e.norm() - (below - base).norm(), UnitVec3::squared(e))
            }
            _ => (ht - hf, axis),
        };
        // A ruling piece from `a` to `b` on the ruling through `on`.
        let piece = |a: Point3<T>, b: Point3<T>, on: Point3<T>| match *self {
            Self::Cone { .. } => {
                let e = on - base;
                Piece::Segment {
                    from: a,
                    to: b,
                    ruling: e.normalize(),
                    lever: geom_brep::ExtentBall::point(base).lever_from(on),
                }
            }
            _ => Piece::Ruling { from: a, to: b },
        };
        let rise = decide(
            "split_ring_path_rise",
            Margin::of(charge(rise, slack)),
            band,
        )?;
        let round_at_to = parallel((base + axis.get() * ht, axis.get()), rt, turned, to);
        let turn = decide(
            "split_ring_path_turn",
            Margin::of(charge(
                (round_at_to.span.1 - round_at_to.span.0) * rt,
                slack,
            )),
            band,
        )?;
        let mut paths = Vec::with_capacity(2);
        if turn != Sign::Zero {
            paths.push(Path {
                pieces: vec![piece(from, turned, from), Piece::Arc(round_at_to)],
                arrival: round_at_to.tangent(round_at_to.span.1),
                reach: None,
            });
        }
        if rise != Sign::Zero {
            let round = parallel((base + axis.get() * hf, axis.get()), rf, from, below);
            paths.push(Path {
                pieces: vec![Piece::Arc(round), piece(below, to, to)],
                arrival: if rise == Sign::Positive {
                    ruling_at_to.get()
                } else {
                    -ruling_at_to.get()
                },
                reach: None,
            });
        }
        Ok(paths)
    }
}

impl<T: Decide> Quadric<T> {
    /// **The turns of a detour** to `to` on a cylinder or a cone,
    /// steered by `guide`: the corners of the ruled paths from `guide`
    /// to `to` ([`ruled_corners`]), `to`'s parallel at `guide`'s azimuth
    /// and `to`'s ruling at `guide`'s height. Each is a raw pick: a path
    /// through any point has the parity of every other. None on any
    /// other kind, nor where `guide` or `to` is decided on a cone's apex,
    /// where a turn has no azimuth; an escalation where either is read
    /// in band of it ([`Self::off_apex`]). Every point of a cylinder is
    /// off its axis by the radius.
    fn turns(
        &self,
        to: Point3<T>,
        guide: Point3<T>,
        band: Band,
    ) -> Result<Vec<Point3<T>>, Indeterminate> {
        match *self {
            Self::Cylinder { axis, .. } => Ok(ruled_corners(axis, (guide, to)).to_vec()),
            Self::Cone { axis, .. } => {
                Ok(if self.off_apex(guide, band)? && self.off_apex(to, band)? {
                    ruled_corners(axis, (guide, to)).to_vec()
                } else {
                    Vec::new()
                })
            }
            Self::Sphere { .. } | Self::Torus { .. } => Ok(Vec::new()),
        }
    }
}

/// **The corners of the ruled paths** from `from` to `to` on the
/// cylinder or cone about `line`: `to`'s parallel at `from`'s azimuth,
/// where the path along `from`'s ruling turns, and `from`'s parallel at
/// `to`'s azimuth, where the path round `from`'s parallel turns. Each
/// lies at the radius of the end on its parallel, not at the carrier's
/// ratio, so the pieces meet exactly ([`Quadric::ruled_paths`]). Both
/// ends lie off the axis.
fn ruled_corners<T: Decide>(
    line: geom::Line<T>,
    (from, to): (Point3<T>, Point3<T>),
) -> [Point3<T>; 2] {
    let (hf, wf) = line.param_and_offset(from);
    let (ht, wt) = line.param_and_offset(to);
    let (rf, rt) = (wf.norm(), wt.norm());
    [
        line.origin + line.dir.get() * ht + (wf / rf) * rt,
        line.origin + line.dir.get() * hf + (wt / rt) * rf,
    ]
}

impl<T: Real> Path<T> {
    /// This path, then `next` from where this one arrives.
    fn then(mut self, next: &Self) -> Self {
        self.pieces.extend(next.pieces.iter().cloned());
        self.arrival = next.arrival;
        self.reach = next.reach;
        self
    }
}

/// **A great circle's frame** on the axis `axis`, the direction of
/// `a × b`, whose sine the path decided positive, levered over the arc
/// (`split_ring_path_span`), and `a`, one end's direction from the
/// centre: the frame they state ([`geom_core::RigidMotion::squared`]),
/// its stated-point read at an enclosure scalar kept. The decision is
/// the path's own, so nothing is decided again here.
fn great_circle<T: Real>(centre: Point3<T>, axis: Vec3<T>, a: Vec3<T>) -> geom::Frame<T> {
    geom::Frame::of_motion(&geom_core::RigidMotion::squared(centre, axis, a))
}

/// The arc of the circle centred `centre` about the unit `axis`, of
/// radius `radius`, from `from` to `to` (both in its plane), the short
/// way round: a parallel, or a torus's meridian.
fn parallel<T: Decide>(
    (centre, axis): (Point3<T>, Vec3<T>),
    radius: T,
    from: Point3<T>,
    to: Point3<T>,
) -> CircleArc<T> {
    let u = from - centre;
    let u = u.normalize();
    let w = to - centre;
    let phi = w.dot(axis.cross(u)).atan2(w.dot(u));
    // The way round is a raw pick: either is a path between the same
    // ends, and the parity is the same on every path.
    CircleArc {
        circle: geom::Circle::new(
            geom::Frame::new(centre, axis * phi.select_le_zero(-T::one(), T::one()), u),
            radius,
        ),
        span: (T::zero(), phi.abs()),
    }
}

/// A circle arc, travelled with its parameter over the increasing
/// `span`.
#[derive(Clone, Copy)]
struct CircleArc<T: Real> {
    circle: geom::Circle<T>,
    span: (T, T),
}

impl<T: Real> CircleArc<T> {
    fn at(&self, t: T) -> Point3<T> {
        self.circle.point_at(t)
    }

    /// The unit direction of travel at `t`.
    fn tangent(&self, t: T) -> Vec3<T> {
        self.circle.derivative_at(t) / self.circle.radius()
    }
}

impl<T: Decide> CircleArc<T> {
    /// The arc's carrier: what its in-span readings take its period from.
    fn carrier(&self) -> geom::Curve3<T> {
        geom::Curve3::Circle(self.circle)
    }

    /// The parameter of `p` (a point of the circle) within half a turn of
    /// the span's middle.
    fn param(&self, p: Point3<T>) -> T {
        self.circle.param_in(p, self.span)
    }
}

/// A piece of a [`Path`].
#[derive(Clone)]
enum Piece<T: Real> {
    /// An arc of an iso curve of a spline wall's chart.
    Iso(IsoPiece<T>),
    /// An arc of a great circle, or of a parallel of a cone or a torus.
    Arc(CircleArc<T>),
    /// An arc of a torus's meridian (a circle round the tube, in a plane
    /// holding the axis).
    Meridian(CircleArc<T>),
    /// A segment of a cylinder's ruling.
    Ruling { from: Point3<T>, to: Point3<T> },
    /// A segment of the cone's ruling `ruling` (unit, from the apex),
    /// whose distance from the apex at `from` is `lever`.
    Segment {
        from: Point3<T>,
        to: Point3<T>,
        ruling: Vec3<T>,
        lever: Lever<T>,
    },
}

/// A path on a [`Carrier`] between two points, its unit direction of
/// travel where it arrives, and, on a spline wall, the arm that
/// arrival's lean is levered at ([`spline_wall::IsoPiece::reach`]): a
/// quadric's is its own at the point arrived at ([`Quadric::lever`]).
#[derive(Clone)]
pub(crate) struct Path<T: Real> {
    pieces: Vec<Piece<T>>,
    pub(crate) arrival: Vec3<T>,
    pub(crate) reach: Option<Lever<T>>,
}

/// The surface a path runs on: a [`Quadric`], or a spline wall.
#[derive(Clone)]
pub(crate) enum Carrier<T: Real> {
    Quadric(Quadric<T>),
    Wall(SplineWall<T>),
}

impl<T: Decide> Carrier<T> {
    /// The carrier of `surface`; `None` for a plane, and for a spline
    /// whose iso curves the paths do not read ([`SplineWall::of`]).
    pub(crate) fn of(surface: &geom::Surface<T>) -> Option<Self> {
        Quadric::of(surface)
            .map(Self::Quadric)
            .or_else(|| SplineWall::of(surface).map(Self::Wall))
    }

    /// The paths from `from` to `to` ([`Quadric::paths`],
    /// [`SplineWall::paths`]).
    pub(crate) fn paths(
        &self,
        ends: (Point3<T>, Point3<T>),
        band: Band,
    ) -> Result<Vec<Path<T>>, Indeterminate> {
        match self {
            Self::Quadric(quadric) => quadric.paths(ends, band),
            Self::Wall(wall) => wall.paths(ends, band),
        }
    }

    /// **The detours from `from` to `to` steered by `guide`**, one
    /// offer per turn of [`Quadric::turns`]: every path to the turn
    /// followed by every path from it to `to`. A ruled path whose pieces
    /// run through a loop's vertices, as every one does where the ends
    /// share their azimuths and heights with them, says nothing; a turn
    /// at the azimuth or the height of a point inside a loop edge, which
    /// no vertex that edge joins has, leads round them. A turn whose
    /// paths escalate is that offer's escalation alone. None on a
    /// sphere, a torus or a spline wall.
    pub(crate) fn detours(
        &self,
        (from, to): (Point3<T>, Point3<T>),
        guide: Point3<T>,
        band: Band,
    ) -> Vec<Result<Vec<Path<T>>, Indeterminate>> {
        let Self::Quadric(quadric) = self else {
            return Vec::new();
        };
        let turns = match quadric.turns(to, guide, band) {
            Ok(turns) => turns,
            Err(diag) => return vec![Err(diag)],
        };
        turns
            .into_iter()
            .map(|turn| {
                let onward = quadric.paths((turn, to), band)?;
                let firsts = quadric.paths((from, turn), band)?;
                Ok(firsts
                    .iter()
                    .flat_map(|first| onward.iter().map(|next| first.clone().then(next)))
                    .collect())
            })
            .collect()
    }

    /// The length the lean of `path`'s arrival at `q` on `surface`, the
    /// surface this carrier is of, is levered by: the arm the path states
    /// ([`Path::reach`], a spline wall's), else a quadric's own at `q`
    /// ([`Quadric::lever`]). `None` for a path on a spline wall that
    /// states none, which says nothing.
    pub(crate) fn lean_lever(
        &self,
        surface: &geom::Surface<T>,
        q: Point3<T>,
        path: &Path<T>,
    ) -> Option<Lever<T>> {
        match (path.reach, self) {
            (Some(reach), _) => Some(reach),
            (None, Self::Quadric(quadric)) => Some(quadric.lever(surface, q)),
            (None, Self::Wall(_)) => None,
        }
    }
}

/// An arc of a section conic, a circle or an ellipse carrier, over its
/// increasing span.
#[derive(Clone)]
pub(crate) struct ConicArc<T: Real> {
    /// A `Circle` or an `Ellipse` carrier.
    carrier: geom::Curve3<T>,
    span: (T, T),
    /// On a torus, the side of its plane's two loops the conic's own
    /// circle lies on; `None` where the plane cuts the surface in the
    /// conic alone.
    own: Option<ArcLoop<T>>,
}

#[cfg(test)]
impl ConicArc<f64> {
    /// A test arc over `span` of the conic placed by `frame` with
    /// semi-axes `(a, b)`: a circle where they are equal.
    pub(crate) fn of_frame(
        frame: geom::Frame<f64>,
        (a, b): (f64, f64),
        span: (f64, f64),
        own: Option<ArcLoop<f64>>,
    ) -> Self {
        #[allow(clippy::float_cmp)]
        let carrier = if a == b {
            geom::Curve3::Circle(geom::Circle::new(frame, a))
        } else {
            geom::Curve3::Ellipse(geom::Ellipse::new(frame, a, b))
        };
        Self { carrier, span, own }
    }
}

impl<T: Real> ConicArc<T> {
    /// The carrier read as a conic.
    fn conic(&self) -> &dyn Conic<T> {
        self.carrier
            .conic()
            .unwrap_or_else(|| unreachable!("a conic arc's carrier is a circle or an ellipse"))
    }
}

/// An arc of a spiric oval on a torus over its increasing span
/// (`centre + u_ref·offset + m·f(t) + axis·minor·sin t`,
/// `m = axis × u_ref`, `f = √((major + minor·cos t)² − offset²)`, the
/// carrier's own form): one of the two loops its plane parallel to the
/// axis cuts, on the `+m` side of the axis's trace (`own`). Its
/// parameter is the torus's minor angle at a point, and its speed in it
/// is at least `minor`.
#[derive(Clone, Copy)]
pub(crate) struct Oval<T: Real> {
    /// The spiric carrier's frame, as the carrier holds it.
    frame: geom::Frame<T>,
    major: T,
    minor: T,
    offset: T,
    /// Its plane's frame: the axis the spiric's `u_ref`, kept bit for bit.
    plane: geom::Frame<T>,
    span: (T, T),
    /// The side of its plane's two loops the oval's own lies on; `None`
    /// only where a row strips it to show what it guards.
    own: Option<ArcLoop<T>>,
}

/// An arc of a loop on a cylinder, sphere, cone, torus or spline face,
/// over its increasing span: a section conic, a spiric oval, a ruling
/// (`origin + dir·t`) or a spline, which is all a spline face's is.
#[derive(Clone)]
pub(crate) enum LoopArc<T: Real> {
    Conic(ConicArc<T>),
    Line {
        line: geom::Line<T>,
        span: (T, T),
    },
    Oval(Oval<T>),
    /// An arc of a torus's top or bottom circle, the parallel of radius
    /// `R`, whose plane touches the torus along it. A path meets it only where
    /// it crosses the cylinder `ρ = R` about the torus's axis, which cuts
    /// the torus transversally in this circle and the one across the tube
    /// (`own` tells them apart by the height along the axis).
    Crest {
        circle: geom::Circle<T>,
        span: (T, T),
        /// The torus's centre, unit axis and major radius `R`.
        core: (Point3<T>, UnitVec3<T>, T),
        own: ArcLoop<T>,
    },
    /// An arc of a spline carrier known to lie on the face's surface
    /// ([`SplineArc`]), whose meetings with a path's piece are the
    /// curve-pair table's ([`geom_brep::curve_pair::meet`]).
    Spline(SplineArc<T>),
}

/// **A spline arc on a cylinder, a sphere, a torus or a spline face,
/// with the evidence that it lies on the face's surface to within the
/// band.**
///
/// [`spline_crossings`] reads a spline arc's meetings with a path's
/// pieces through the curve-pair table, which finds the points where
/// two curves meet in space. A path lies on the surface and a crossing of
/// the arc on the surface is a meeting in space only where the arc lies
/// on the surface too: an arc standing off it by more than the band
/// passes near the path instead and is read as missing it, which
/// miscounts the parity. So a spline arc is made only where that
/// distance is certified, by one of two constructors:
///
/// - [`Self::of_edge`]: a certified edge whose description is the
///   intersection of the face's surface with another, which the edge
///   door certified by C2's limb 2 against each (its distance zero in
///   the band);
/// - [`Self::of_section`]: an arc of a component the general rung fitted
///   with its three-limb certificate against both surfaces of the
///   section, the chord a join is about to mint from it.
///
/// Both are read on a cylinder, a sphere, a torus or a spline face: the
/// faces a carried chord bounds, which the ring lane's rows read
/// (`ring_path::tests`, `ring_path::spline_wall_rows`). A spline wall's
/// pieces are its own iso curves, which lie on it. Every piece of a
/// torus path past its lead lies on the tube through its end, within the band of the face's own, so the
/// argument is the cylinder's: a crossing on the surface is a meeting in
/// space. The lead, which moves the start onto that tube along its own
/// tube radius, is off the surface but no longer than the two ends'
/// offsets from it, within the band: an arc meeting it meets it within
/// the band of the path's start, which the curve-pair table reads at the
/// lead's span end, and there the path says nothing ([`spline_crossings`])
/// and the caller asks another.
#[derive(Clone)]
pub(crate) struct SplineArc<T: Real> {
    carrier: geom::Curve3<T>,
    span: (T, T),
}

impl<T: Decide> SplineArc<T> {
    /// The arc of a spline `carrier` over the span: a clamped spline as
    /// it is, a periodic cubic as its clamped view over the span, which
    /// is what the arc's readers read. `None` for any other carrier, and
    /// for a span a periodic cubic has no view over.
    fn spline(carrier: &geom::Curve3<T>, (t0, t1): (T, T)) -> Option<Self> {
        let span = (t0.min(t1), t0.max(t1));
        let net = carrier.clamped_net(span)?.ok()?;
        Some(Self {
            carrier: geom::Curve3::Nurbs(net),
            span,
        })
    }

    /// The arc of `curve`, a certified spline edge described as the
    /// intersection of `surface` (the face's) and another; `None` for
    /// any other edge.
    pub(crate) fn of_edge(
        curve: &geom_brep::EdgeCurve<T>,
        surface: crate::geometry::SurfaceKey,
    ) -> Option<Self> {
        match curve.description() {
            geom_brep::EdgeDescription::Intersection { pair, .. } if pair.contains(surface) => {
                Self::spline(curve.carrier(), curve.params())
            }
            _ => None,
        }
    }

    /// The arc of `carrier` over `params`, cut from `component`, a
    /// fitted component of a section of the face's surface; `None` for a
    /// component with no certificate.
    pub(crate) fn of_section(
        component: &geom_brep::CarriedComponent<T>,
        carrier: &geom::Curve3<T>,
        params: (T, T),
    ) -> Option<Self> {
        component
            .certificate
            .as_ref()
            .and_then(|_| Self::spline(carrier, params))
    }

    /// A fixture's arc, whose spline lies on the surface by construction.
    #[cfg(test)]
    pub(crate) fn on_by_construction(carrier: &geom::Curve3<T>, params: (T, T)) -> Option<Self> {
        Self::spline(carrier, params)
    }
}

impl<T: Real> LoopArc<T> {
    /// The arc of `carrier` between the parameters `t0` and `t1`;
    /// `None` on a spiric, which only a torus carries
    /// ([`Quadric::torus_spiric_arc`]), and on a spline, which carries
    /// its evidence ([`SplineArc`]).
    pub(crate) fn of(carrier: &geom::Curve3<T>, (t0, t1): (T, T)) -> Option<Self> {
        let span = (t0.min(t1), t0.max(t1));
        match *carrier {
            geom::Curve3::Circle(_) | geom::Curve3::Ellipse(_) => Some(Self::Conic(ConicArc {
                carrier: carrier.clone(),
                span,
                own: None,
            })),
            geom::Curve3::Line(line) => Some(Self::Line { line, span }),
            geom::Curve3::Nurbs(_) | geom::Curve3::Periodic(_) | geom::Curve3::Spiric { .. } => {
                None
            }
        }
    }

    /// The straight arc from `from` to `to`.
    pub(crate) fn segment(from: Point3<T>, to: Point3<T>) -> Self {
        let d = to - from;
        let (_, length) = d.direction_and_length();
        Self::Line {
            line: geom::Line {
                origin: from,
                dir: UnitVec3::squared(d),
            },
            span: (T::zero(), length),
        }
    }
}

impl<T: Decide> LoopArc<T> {
    /// **A section arc's plane and its reading at a point of it**, for
    /// a conic or a spiric oval: the plane (a point of it and its unit
    /// normal), the arc's span, the least speed of its parameter (metres
    /// per radian: a conic's minor semi-axis, an oval's tube radius),
    /// which levers an in-span reading, and the side of its plane's two
    /// loops its own lies on. `None` for a ruling or a crest.
    #[expect(
        clippy::disallowed_methods,
        reason = "a conic's centre frame, derived where an ellipse is held on its arc: owed a reading through the conic (work/oneround/one-stored-form-waits-on-the-readers-of-a-conics-centre.md)"
    )]
    fn plane(&self) -> Option<SectionArc<T>> {
        match self {
            Self::Conic(c) => Some(SectionArc {
                plane: c.conic().frame(),
                span: c.span,
                speed: c.conic().speed_lo(),
                own: c.own,
            }),
            &Self::Oval(o) => Some(SectionArc {
                plane: o.plane,
                span: o.span,
                speed: o.minor,
                own: o.own,
            }),
            Self::Line { .. } | Self::Crest { .. } | Self::Spline { .. } => None,
        }
    }

    /// The parameter of `x`, a point of a section arc's plane, on the
    /// branch of its span's middle ([`Conic::param_in`], [`Oval::param`]).
    /// A ruling or a crest has none.
    fn param_at(&self, x: Point3<T>) -> Option<T> {
        match self {
            Self::Conic(c) => Some(c.conic().param_in(x, c.span)),
            Self::Oval(o) => Some(o.param(x)),
            Self::Line { .. } | Self::Crest { .. } | Self::Spline { .. } => None,
        }
    }
}

impl<T: Decide> Oval<T> {
    /// The oval's carrier.
    fn carrier(&self) -> geom::Curve3<T> {
        geom::Curve3::Spiric {
            frame: self.frame,
            major_radius: self.major,
            minor_radius: self.minor,
            offset: self.offset,
        }
    }

    /// The parameter of `x`, a point of the oval's plane, on the branch
    /// of its span's middle: the carrier's own reading.
    fn param(&self, x: Point3<T>) -> T {
        let mid = geom::mid_param(self.span.0, self.span.1);
        match self.carrier().param_near(x, mid) {
            Some(t) => t,
            None => unreachable!("a spiric carrier reads every point's parameter"),
        }
    }
}

/// A section arc's plane and the length its in-span readings are
/// levered by ([`LoopArc::plane`]).
#[derive(Clone, Copy)]
struct SectionArc<T: Real> {
    plane: geom::Frame<T>,
    span: (T, T),
    speed: T,
    own: Option<ArcLoop<T>>,
}

/// **Which of two loops of one plane section a point lies on**: the sign
/// of a margin in metres, definite at every point of a served section.
/// The boolean join reads it at a germ site (`boolean::join`'s
/// `SectionLoops`), and the ring lane at a crossing of a torus loop
/// arc's plane ([`ArcLoop`]).
#[derive(Clone, Copy, Debug)]
pub(crate) enum LoopSplit<T: Real> {
    /// `(p − origin)·dir`, `dir` unit.
    Side {
        /// A point of the plane between the loops.
        origin: Point3<T>,
        /// That plane's unit normal.
        dir: Vec3<T>,
    },
    /// `p`'s distance from the axis less `radius`.
    Radius {
        /// The axis. Only [`geom::Line::distance`] reads it, which is
        /// correct for any nonzero `dir`, so a unit `dir` is not a premise
        /// here (`an-axis-reads-its-direction-as-unit-by-convention-not-type`).
        axis: geom::Line<T>,
        /// The radius between the loops.
        radius: T,
    },
}

impl<T: Real> LoopSplit<T> {
    /// The margin at `p`: positive on the split's positive loop.
    pub(crate) fn margin(&self, p: Point3<T>) -> T {
        match *self {
            Self::Side { origin, dir } => geom::plane_offset(origin, dir, p),
            Self::Radius { axis, radius } => axis.distance(p) - radius,
        }
    }

    /// **The split of a plane×torus section's two loops**, the one
    /// reading the boolean join's frame (`boolean::join`'s
    /// `pt_germ_frame`) and the chord (`chord_join::section_case`) both
    /// take, so that they name one loop. The torus is `(centre, axis,
    /// R)` and `n` the plane's normal.
    ///
    /// - The meridian circles and the spiric ovals: the side of the
    ///   plane through the axis square to the cut, the first loop on the
    ///   positive side.
    /// - The concentric circles: the distance from the axis against `R`,
    ///   the outer circle positive.
    ///
    /// `None` for a section with no two loops, or a meridian section
    /// whose first loop is no circle.
    #[expect(
        clippy::disallowed_methods,
        reason = "a circle's centre frame, which a circle stores: owed a reading through the conic (work/oneround/one-stored-form-waits-on-the-readers-of-a-conics-centre.md)"
    )]
    pub(crate) fn plane_torus(
        section: &geom_brep::PlaneTorusSection<T>,
        (centre, axis, major): (Point3<T>, Vec3<T>, T),
        n: Vec3<T>,
    ) -> Option<Self> {
        match section {
            geom_brep::PlaneTorusSection::MeridianCircles {
                c1: geom::Curve3::Circle(the_circle @ geom::Circle { .. }),
                ..
            } => {
                let frame = the_circle.frame();
                let center = frame.origin();
                Some(Self::Side {
                    origin: centre,
                    dir: (center - centre).normalize(),
                })
            }
            geom_brep::PlaneTorusSection::SpiricOvals { .. } => Some(Self::Side {
                origin: centre,
                dir: axis.cross(n).normalize(),
            }),
            geom_brep::PlaneTorusSection::ConcentricCircles { .. } => Some(Self::Radius {
                axis: geom::Line {
                    origin: centre,
                    dir: UnitVec3::squared(axis),
                },
                radius: major,
            }),
            geom_brep::PlaneTorusSection::MeridianCircles { .. }
            | geom_brep::PlaneTorusSection::TangentCircle(_)
            | geom_brep::PlaneTorusSection::Empty => None,
        }
    }
}

/// **Which of its plane's two loops on a torus a loop arc's circle is**:
/// the split between them and the circle's side of it. A meridian's
/// plane holds the axis and cuts the meridian across it too, `2(R − r)`
/// or more away: the split is the plane through the axis square to it,
/// the circle on the side of `ê`, toward its centre. A parallel's plane
/// cuts the parallel across the tube: the split is the core radius `R`,
/// the outer parallel on its positive side. Both are the boolean join's
/// loop splits for those sections.
#[derive(Clone, Copy)]
pub(crate) struct ArcLoop<T: Real> {
    split: LoopSplit<T>,
    /// Whether the arc's circle is on the split's positive side.
    positive: bool,
}

impl<T: Decide> ArcLoop<T> {
    /// **`split_ring_path_torus_loop`** at `p`: positive on the arc's
    /// own loop, the margin charged `slack` ([`charge`]).
    fn read(&self, p: Point3<T>, slack: T, band: Band) -> Result<Sign, Indeterminate> {
        let m = self.split.margin(p);
        decide(
            "split_ring_path_torus_loop",
            Margin::of(charge(if self.positive { m } else { -m }, slack)),
            band,
        )
    }
}

impl<T: Decide> Quadric<T> {
    /// **The loop arc of a spiric oval on this torus**, over `params`;
    /// `None` for any other carrier, and on a sphere or a cone. The
    /// oval's plane, parallel to the axis, cuts the torus in it and the
    /// oval across the axis's trace: its own loop is on the carrier's
    /// `+m` side of that trace.
    pub(crate) fn torus_spiric_arc(
        &self,
        carrier: &geom::Curve3<T>,
        (t0, t1): (T, T),
    ) -> Option<LoopArc<T>> {
        let (
            Self::Torus { .. },
            &geom::Curve3::Spiric {
                frame: spiric_frame,
                major_radius,
                minor_radius,
                offset,
            },
        ) = (*self, carrier)
        else {
            return None;
        };
        let (center, axis, u_ref) = (
            spiric_frame.origin(),
            spiric_frame.axis(),
            spiric_frame.u_ref(),
        );
        Some(LoopArc::Oval(Oval {
            frame: spiric_frame,
            major: major_radius,
            minor: minor_radius,
            offset,
            plane: geom::Frame::of_motion(&geom_core::RigidMotion::squared_about(
                center + u_ref * offset,
                spiric_frame.u_ref_unit(),
                axis,
            )),
            span: (t0.min(t1), t0.max(t1)),
            own: Some(ArcLoop {
                split: LoopSplit::Side {
                    origin: center,
                    dir: axis.cross(u_ref),
                },
                positive: true,
            }),
        }))
    }

    /// **The loop arc of a circle on this torus**, over `params`: a
    /// meridian or a parallel, with its [`ArcLoop`]; `Ok(None)` for any
    /// other circle (no plane section of a torus outside the touching
    /// poses is another circle) and on a sphere or a cone. The circle's
    /// axis is decided square to the torus's
    /// (**`split_ring_torus_meridian`**: `n̂·â`, levered at the circle's
    /// radius) or along it (**`split_ring_torus_parallel`**:
    /// `‖n̂ × â‖`, levered at the radius), and a parallel's side, its
    /// radius less `R` (**`split_ring_torus_parallel_side`**). A parallel
    /// of radius `R` in that band is the tube's top or bottom circle,
    /// whose plane touches the torus: its arc is a
    /// [`LoopArc::Crest`], told apart from the other by its centre's
    /// height (**`split_ring_torus_crest`**). None is charged a
    /// coordinate resolution: a section lane mints a circle's axis and
    /// radius from the plane's and the torus's stored directions and
    /// radii, never from a difference of far points
    /// (`box_edge_rows::a_torus_circle_the_section_lane_mints_in_the_box_reads_its_kind_at_the_origin`).
    #[expect(
        clippy::disallowed_methods,
        reason = "a conic's centre frame, derived where an ellipse is held on its arc: owed a reading through the conic (work/oneround/one-stored-form-waits-on-the-readers-of-a-conics-centre.md)"
    )]
    pub(crate) fn torus_circle_arc(
        &self,
        carrier: &geom::Curve3<T>,
        params: (T, T),
        band: Band,
    ) -> Result<Option<LoopArc<T>>, Indeterminate> {
        let (
            Self::Torus {
                axis:
                    geom::Line {
                        origin: centre,
                        dir: axis,
                    },
                major,
                ..
            },
            geom::Curve3::Circle(circle),
        ) = (*self, carrier)
        else {
            return Ok(None);
        };
        let (k, n) = (circle.frame().origin(), circle.axis());
        let radius = circle.radius();
        let (k, n, radius) = (k, n, radius);
        let arm = geom_brep::circle_curvature_arm(circle);
        let Some(LoopArc::Conic(conic)) = LoopArc::of(carrier, params) else {
            return Ok(None);
        };
        let (frame, ra, span) = (conic.conic().frame(), radius, conic.span);
        let arc = |own| {
            LoopArc::Conic(ConicArc {
                own: Some(own),
                ..conic.clone()
            })
        };
        if decide(
            "split_ring_torus_meridian",
            Margin::levered(n.dot(axis.get()), arm),
            band,
        )? == Sign::Zero
        {
            let w = geom::Line {
                origin: centre,
                dir: axis,
            }
            .offset(k);
            return Ok(Some(arc(ArcLoop {
                split: LoopSplit::Side {
                    origin: centre,
                    dir: w.normalize(),
                },
                positive: true,
            })));
        }
        if decide(
            "split_ring_torus_parallel",
            Margin::levered(n.cross(axis.get()).norm(), arm),
            band,
        )? != Sign::Zero
        {
            return Ok(None);
        }
        let positive = match decide(
            "split_ring_torus_parallel_side",
            Margin::of(radius - major),
            band,
        )? {
            Sign::Positive => true,
            Sign::Negative => false,
            Sign::Zero => {
                // The tube's top or bottom circle: its side of the
                // equator plane (**`split_ring_torus_crest`**, the
                // centre's height, `±r` on the torus).
                let top = match decide(
                    "split_ring_torus_crest",
                    Margin::of((k - centre).dot(axis.get())),
                    band,
                )? {
                    Sign::Positive => true,
                    Sign::Negative => false,
                    Sign::Zero => return Ok(None),
                };
                return Ok(Some(LoopArc::Crest {
                    circle: geom::Circle::new(frame, ra),
                    span,
                    core: (centre, axis, major),
                    own: ArcLoop {
                        split: LoopSplit::Side {
                            origin: centre,
                            dir: axis.get(),
                        },
                        positive: top,
                    },
                }));
            }
        };
        Ok(Some(arc(ArcLoop {
            split: LoopSplit::Radius {
                axis: geom::Line {
                    origin: centre,
                    dir: axis,
                },
                radius: major,
            },
            positive,
        })))
    }
}

/// **Whether `path` crosses `arcs` an odd number of times**: whether its
/// ends lie on opposite sides of the closed curve the arcs make (module
/// docs). `arrives_on` names the arc the path's end lies on, at an
/// interior point; its crossing there is the arrival and is not
/// counted. `None` when a reading of a crossing not passed over lands
/// in the zero band; `Err` when one lands in the escalation band, which
/// says nothing about the parity either: the caller asks another path.
/// A crossing is passed over when any of its in-span readings is
/// decided out of span, even where another escalates.
///
/// - A circle piece meets a conic's or an oval's plane where the
///   crossing reading finds it ([`plane_roots`], the plane arm of
///   [`geom_brep::curve_face::cross()`], whose pose decides the gap
///   `r·√(A² + B²) − |D|` uncharged: `A`, `B` the plane normal's
///   components on the piece's frame, `D` the piece's centre's offset
///   from the plane). A graze inside the gap's band escalates, and the
///   caller asks the next path. On the arrival arc, the meeting nearer
///   the piece's end is the arrival. A gap
///   in the zero band is a piece along the plane, which meets no conic
///   arc it is decided apart from ([`misses_in_plane`]): a path's
///   meridian or parallel through a point of an arc's carrier, or of its
///   plane's other loop, runs so.
/// - A segment meets a conic's or an oval's plane where its ends'
///   offsets from it (**`split_ring_path_segment_side`**) differ in
///   sign. A segment decided apart from a conic arc
///   ([`segment_misses`]) meets it nowhere, as a torus path's lead from
///   a point on an arc's plane is. One with an end on the plane and the
///   other decided off it meets the plane once, at that end: the
///   crossing is read as any other, its place on the segment in the zero
///   band, so it is passed over where the arc reads it out of span (a
///   path from a ring vertex on an arc's plane, off the arc) and says
///   nothing otherwise. One with both ends on the plane says nothing
///   unless its length is in the band (**`split_ring_path_lead_point`**:
///   a lead from a point already on its tube) and that point is decided
///   off the arc (on the plane's other loop, or out of the arc's span).
/// - A ruling meets a circle piece's plane once (it is decided across
///   it, **`split_ring_path_line_across`**: the cosine between the
///   plane's normal and the ruling, levered at the piece's radius), and
///   another ruling nowhere off the apex (the two are decided apart,
///   **`split_ring_path_rulings_apart`**: the sine between them,
///   levered at the segment's distance from the apex, and charged each
///   direction's rounding: the resolution over that distance and over
///   the arc's length).
/// - On a torus, a meeting point counts only on the arc's own loop of
///   its plane ([`ArcLoop`], **`split_ring_path_torus_loop`**).
/// - Every reading above is charged the path's resolution
///   ([`path_resolution`], [`charge`]): the spread of its pieces' stored
///   terms and the arcs' stored centres, origins or ends, and a conic
///   arc's own carrier resolution — but the cosine across,
///   read between two directions, and two readings whose zero only hands
///   the case to charged readings, so that a charge would only widen it:
///   the lead's length, and [`misses_in_plane`]'s
///   **`split_ring_path_same_circle`**, whose zero hands the arcs' ends
///   to the in-span readings. Where a stored term lies far from the
///   arc it serves (a section's centre far along its plane), points
///   that should lie on one plane or one circle are stored further apart
///   than the band, and a margin inside their rounding stands down
///   rather than decide.
/// - Each meeting point counts when it lies strictly inside the piece's
///   span and the arc's (**`split_ring_path_in_span`**: the distance
///   along the piece or the arc to a span end — a parameter levered at a
///   circle's radius, a conic's minor semi-axis or an oval's tube radius
///   (each the least speed of its parameter), or a line's length —
///   times the slope the piece crosses the other's plane at. That is the
///   carrier displacement that moves the root past the end: near a graze
///   a root moves by the displacement over the slope, so a span end a
///   decided arc length away can still be inside its reach.)
#[expect(
    clippy::disallowed_methods,
    reason = "a circle's centre frame, which a circle stores: owed a reading through the conic (work/oneround/one-stored-form-waits-on-the-readers-of-a-conics-centre.md)"
)]
pub(crate) fn path_parity<T: Decide>(
    path: &Path<T>,
    arcs: &[LoopArc<T>],
    arrives_on: Option<usize>,
    band: Band,
) -> Result<Option<bool>, Indeterminate> {
    let decide_m = |name, margin| decide(name, margin, band);
    let slack = path_resolution(path, arcs);
    // A crossing's in-span readings are kept whole, escalations included:
    // one decided out of span passes the crossing over whatever the
    // others read.
    // Every in-span reading takes its carrier, whose period it reads
    // ([`span_readings`]).
    let in_span = |carrier: &geom::Curve3<T>, t: T, span: (T, T), arm: T| {
        span_readings(carrier, t, span, arm, slack, band)
    };
    let inside = Ok(Sign::Positive);
    // A crossing of a torus arc's plane on the plane's other loop is no
    // crossing of the arc: its side is one more reading of the crossing.
    let on_own =
        |own: Option<ArcLoop<T>>, x: Point3<T>| own.map_or(inside, |l| l.read(x, slack, band));
    // The arms below that read a section arc match only a conic or an
    // oval, which both have a plane and a parameter.
    let section = |arc: &LoopArc<T>| match arc.plane() {
        Some(sec) => sec,
        None => unreachable!("only a conic or an oval arc is read as a section arc"),
    };
    let param = |arc: &LoopArc<T>, x: Point3<T>| match arc.param_at(x) {
        Some(t) => t,
        None => unreachable!("only a conic or an oval arc is read as a section arc"),
    };
    let carrier = |arc: &LoopArc<T>| match arc {
        LoopArc::Conic(c) => c.carrier.clone(),
        LoopArc::Oval(o) => o.carrier(),
        LoopArc::Line { .. } | LoopArc::Crest { .. } | LoopArc::Spline(_) => {
            unreachable!("only a conic or an oval arc is read as a section arc")
        }
    };
    let last = path.pieces.len().saturating_sub(1);
    // Every piece against every arc, as one ladder ([`climb`],
    // [`Answering::Any`]: a theorem, any pair at which the path says
    // nothing leaves the path saying nothing, and its `None` answers).
    // A pair read in band is kept, refusing only where no pair answers;
    // every other pair flips the parity by its crossings.
    let pairs = path.pieces.iter().enumerate().flat_map(|(i, piece)| {
        arcs.iter()
            .enumerate()
            .map(move |(j, arc)| (i, piece, j, arc))
    });
    let mut odd = false;
    let climbed = climb(Answering::Any, pairs, |(i, piece, j, arc)| {
        // `None` where the path says nothing at this pair; else whether
        // its crossings flip the parity.
        let pair = || -> Result<Option<bool>, Indeterminate> {
            let mut flip = false;
            let arrival = i == last && arrives_on == Some(j);
            let mut readings: Vec<[Result<Sign, Indeterminate>; 5]> = Vec::with_capacity(2);
            match (piece.clone(), arc.clone()) {
                (Piece::Arc(p) | Piece::Meridian(p), LoopArc::Conic(_) | LoopArc::Oval(_)) => {
                    let sec = section(arc);
                    // A conic decided apart from the piece's circle misses
                    // it whatever the planes ([`coplanar_apart`]), so it
                    // answers past a plane meeting read in band.
                    let apart = |conic: &ConicArc<T>| {
                        !arrival && coplanar_apart(&p, conic, slack, band) == Ok(true)
                    };
                    let roots = match plane_roots(&p, &sec.plane, arrival, band) {
                        Ok(PlaneMeet::Meets(roots)) => roots,
                        Ok(PlaneMeet::Along) => {
                            if let LoopArc::Conic(conic) = arc
                                && !arrival
                                && misses_in_plane(&p, conic, slack, band)?
                            {
                                return Ok(Some(flip));
                            }
                            return Ok(None);
                        }
                        Ok(PlaneMeet::Unread) => {
                            return Ok(match arc {
                                LoopArc::Conic(conic) if apart(conic) => Some(flip),
                                _ => None,
                            });
                        }
                        Err(diag) => {
                            return match arc {
                                LoopArc::Conic(conic) if apart(conic) => Ok(Some(flip)),
                                _ => Err(diag),
                            };
                        }
                    };
                    for (m, slope) in roots {
                        let t = m.t();
                        let [p0, p1] = m.readings();
                        let [a0, a1] = in_span(
                            &carrier(arc),
                            param(arc, p.at(t)),
                            sec.span,
                            sec.speed * slope,
                        );
                        readings.push([p0, p1, a0, a1, on_own(sec.own, p.at(t))]);
                    }
                }
                // A crest is a torus's, whose paths' arcs are parallels
                // (`Piece::Arc`) and meridians. A parallel keeps its
                // distance from the axis, so it meets the cylinder
                // `ρ = R` nowhere unless it runs along it
                // (**`split_ring_path_crest_graze`**: its radius less `R`).
                (
                    Piece::Arc(p),
                    LoopArc::Crest {
                        core: (.., major), ..
                    },
                ) => {
                    if decide_m(
                        "split_ring_path_crest_graze",
                        Margin::of(charge(p.circle.radius() - major, slack)),
                    )? == Sign::Zero
                    {
                        return Ok(None);
                    }
                }
                // A meridian lies in a plane holding the axis, where
                // `ρ − R` is the offset from its centre on the core along
                // the radial `ê`: it crosses the cylinder `ρ = R` where it
                // crosses the plane through its centre square to `ê`, on
                // the tube's top and bottom.
                (
                    Piece::Meridian(p),
                    LoopArc::Crest {
                        circle,
                        span,
                        core: (c, a, _),
                        own,
                    },
                ) => {
                    let e = geom::Line { origin: c, dir: a }.offset(p.circle.frame().origin());
                    let e = e.normalize();
                    let PlaneMeet::Meets(roots) = plane_roots(
                        &p,
                        // `ê` is square to the axis `a`, which seams the plane.
                        &geom::Frame::new(p.circle.frame().origin(), e, a.get()),
                        arrival,
                        band,
                    )?
                    else {
                        return Ok(None);
                    };
                    for (m, slope) in roots {
                        let t = m.t();
                        let s = circle.param_in(p.at(t), span);
                        let [p0, p1] = m.readings();
                        let [a0, a1] = in_span(
                            &geom::Curve3::Circle(circle),
                            s,
                            span,
                            circle.radius() * slope,
                        );
                        readings.push([p0, p1, a0, a1, own.read(p.at(t), slack, band)]);
                    }
                }
                // The torus's one segment is the lead along a tube radius,
                // in a meridian half-plane, where `ρ − R` is a multiple of
                // its offset from the core point at its start, so it keeps
                // its sign (**`split_ring_path_crest_side`**). A segment
                // whose ends are decided across the cylinder is no lead,
                // and says nothing.
                (
                    Piece::Segment { from, to, .. },
                    LoopArc::Crest {
                        core: (c, a, major),
                        ..
                    },
                ) => {
                    if arrival {
                        return Ok(Some(flip));
                    }
                    let rho_less =
                        |p: Point3<T>| geom::Line { origin: c, dir: a }.distance(p) - major;
                    let side = |p| {
                        decide_m(
                            "split_ring_path_crest_side",
                            Margin::of(charge(rho_less(p), slack)),
                        )
                    };
                    // Either end decided on the cylinder answers alone, so
                    // both are read before either refuses.
                    let (s0, s1) = (side(from), side(to));
                    if [s0, s1].contains(&Ok(Sign::Zero)) {
                        return Ok(None);
                    }
                    if s0? != s1? {
                        return Ok(None);
                    }
                }
                (
                    Piece::Arc(p) | Piece::Meridian(p),
                    LoopArc::Line {
                        line: geom::Line { origin, dir },
                        span,
                    },
                ) => {
                    let across = p.circle.axis().dot(dir.get());
                    if decide_m(
                        "split_ring_path_line_across",
                        Margin::levered(across, geom_brep::circle_curvature_arm(&p.circle)),
                    )? == Sign::Zero
                    {
                        return Ok(None);
                    }
                    if arrival {
                        return Ok(Some(flip));
                    }
                    let s = p.circle.axis().dot(p.circle.frame().origin() - origin) / across;
                    let t = p.param(origin + dir.get() * s);
                    // The plane moved by δ moves the root by δ over the
                    // slope the ruling crosses it at, `|m̂·d̂|`.
                    let slope = across.abs();
                    let [p0, p1] = in_span(&p.carrier(), t, p.span, p.circle.radius() * slope);
                    let ruling = geom::Curve3::Line(geom::Line { origin, dir });
                    let [a0, a1] = in_span(&ruling, s, span, slope);
                    readings.push([p0, p1, a0, a1, inside]);
                }
                (
                    Piece::Segment { from, to, .. } | Piece::Ruling { from, to },
                    LoopArc::Conic(_) | LoopArc::Oval(_),
                ) => {
                    if arrival {
                        return Ok(Some(flip));
                    }
                    let sec = section(arc);
                    let offset = |x: Point3<T>| sec.plane.height(x);
                    let (d0, d1) = (offset(from), offset(to));
                    let side =
                        |d| decide_m("split_ring_path_segment_side", Margin::of(charge(d, slack)));
                    let (s0, s1) = (side(d0), side(d1));
                    // A segment decided apart from a conic arc meets it
                    // nowhere. One along the plane says nothing unless its
                    // length is in the band: the lead from a point already
                    // on the tube it moves onto, which meets the arc
                    // nowhere where that point is decided off it (on the
                    // plane's other loop, or out of the arc's span, read at
                    // the arc's least speed).
                    // Either end decided on the plane lets the miss answer
                    // without the other end, so the miss is read before
                    // either end's refusal; past it, both ends are needed.
                    if [s0, s1].contains(&Ok(Sign::Zero))
                        && let LoopArc::Conic(conic) = arc
                        && segment_misses((from, to), conic, slack, band)?
                    {
                        return Ok(Some(flip));
                    }
                    let (s0, s1) = (s0?, s1?);
                    if s0 == Sign::Zero && s1 == Sign::Zero {
                        let point =
                            decide_m("split_ring_path_lead_point", Margin::of((to - from).norm()))?
                                == Sign::Zero;
                        if !point {
                            return Ok(None);
                        }
                        let [a0, a1] =
                            in_span(&carrier(arc), param(arc, from), sec.span, sec.speed);
                        let reading = [a0, a1, on_own(sec.own, from)];
                        if reading.contains(&Ok(Sign::Negative)) {
                            return Ok(Some(flip));
                        }
                        if let Some(&Err(diag)) = reading.iter().find(|r| r.is_err()) {
                            return Err(diag);
                        }
                        return Ok(None);
                    }
                    if s0 == s1 {
                        return Ok(Some(flip));
                    }
                    let x = from + (to - from) * (d0 / (d0 - d1));
                    // The plane moved by δ moves the root by δ over the
                    // slope the segment crosses it at, `|n̂·d̂|`.
                    let slope = ((d0 - d1) / (to - from).norm()).abs();
                    let [a0, a1] =
                        in_span(&carrier(arc), param(arc, x), sec.span, sec.speed * slope);
                    // With one end on the plane and the other decided off
                    // it, the segment meets the plane once, at that end:
                    // the crossing's place on the segment is in the zero
                    // band, so it is passed over where the arc reads it
                    // out of span or on the plane's other loop, and says
                    // nothing otherwise.
                    let on_end = if s0 == Sign::Zero || s1 == Sign::Zero {
                        Ok(Sign::Zero)
                    } else {
                        inside
                    };
                    readings.push([on_end, inside, a0, a1, on_own(sec.own, x)]);
                }
                (
                    Piece::Segment { ruling, lever, .. },
                    LoopArc::Line {
                        line: geom::Line { dir, .. },
                        span,
                    },
                ) => {
                    if arrival {
                        return Ok(Some(flip));
                    }
                    // Each direction's sine carries its ends' rounding
                    // over their distance: the ruling's over the lever,
                    // the arc's over its length.
                    let rounding = slack / lever.length() + slack / (span.1 - span.0);
                    if decide_m(
                        "split_ring_path_rulings_apart",
                        Margin::levered(charge(ruling.cross(dir.get()).norm(), rounding), lever),
                    )? != Sign::Positive
                    {
                        return Ok(None);
                    }
                }
                // Two rulings of a cylinder are parallel, and meet nowhere
                // where they are decided apart
                // (**`split_ring_path_rulings_distinct`**: the distance
                // between their lines, charged `slack`).
                (
                    Piece::Ruling { from, .. },
                    LoopArc::Line {
                        line: geom::Line { origin, dir },
                        ..
                    },
                ) => {
                    if arrival {
                        return Ok(Some(flip));
                    }
                    let gap = geom::Line { origin, dir }.distance(from);
                    if decide_m(
                        "split_ring_path_rulings_distinct",
                        Margin::of(charge(gap, slack)),
                    )? != Sign::Positive
                    {
                        return Ok(None);
                    }
                }
                // A crest is a torus's, whose paths hold no cylinder ruling.
                (Piece::Ruling { .. }, LoopArc::Crest { .. }) => return Ok(None),
                // An iso piece is read against a spline arc alone: of any
                // other arc the path says nothing.
                (
                    Piece::Iso(_),
                    LoopArc::Conic(_)
                    | LoopArc::Oval(_)
                    | LoopArc::Line { .. }
                    | LoopArc::Crest { .. },
                ) => return Ok(None),
                // A spline arc meets a piece where the curve-pair table
                // says ([`spline_crossings`]).
                (piece, LoopArc::Spline(arc)) => {
                    match spline_crossings(&piece, &arc, arrival, slack, band)? {
                        Some(n) => {
                            if n % 2 == 1 {
                                flip = !flip;
                            }
                        }
                        None => return Ok(None),
                    }
                }
            }
            for reading in readings {
                if reading.contains(&Ok(Sign::Negative)) {
                    continue;
                }
                if let Some(&Err(diag)) = reading.iter().find(|r| r.is_err()) {
                    return Err(diag);
                }
                if reading.contains(&Ok(Sign::Zero)) {
                    return Ok(None);
                }
                flip = !flip;
            }
            Ok(Some(flip))
        };
        match pair() {
            Ok(None) => Rung::Answers(()),
            Ok(Some(flip)) => {
                odd ^= flip;
                Rung::Passes
            }
            Err(diag) => Rung::kept(diag),
        }
    });
    match climbed {
        Climb::Answered { .. } => Ok(None),
        Climb::Passed => Ok(Some(odd)),
        Climb::Undecided(diag) => Err(diag),
    }
}

/// **How many times `piece` crosses the spline arc `arc`**, read through
/// the curve-pair table ([`geom_brep::curve_pair::meet`]), which the
/// arc's evidence of lying on the surface makes a reading of crossings
/// on it ([`SplineArc`]):
/// every meeting it finds lies inside both spans and is a crossing, the
/// sine between the two curves' directions there decided past the band
/// (**`split_ring_path_spline_across`**, levered at the piece's reach
/// from the meeting, from below, whatever the piece's kind, and charged
/// `slack`). The arrival on the closing
/// chord, at the end of the path's last piece, is no crossing before it
/// (`arrival`). `None`
/// where the path says nothing: a meeting at either span's end (the
/// path starts on the arc or runs through its end) or in the zero band
/// of the crossing reading, a shared run, or a meeting the reader could
/// not settle ([`meet_refused`]). An escalation of the reader or of a
/// crossing escalates.
fn spline_crossings<T: Decide>(
    piece: &Piece<T>,
    SplineArc { carrier, span }: &SplineArc<T>,
    arrival: bool,
    slack: T,
    band: Band,
) -> Result<Option<usize>, Indeterminate> {
    use geom_brep::curve_pair::{Hit, Span, SpanEnd, meet};
    // The piece's carrier and span, its length (the no-length reading
    // below), and the span end it stops at.
    let (curve, params, extent, stop) = match piece {
        &(Piece::Arc(p) | Piece::Meridian(p)) => {
            // A piece of no length is a Zero, read at the arc's diameter
            // from above.
            let arc = geom::Curve3::Circle(p.circle);
            let (t0, t1) = p.span;
            let extent = geom_brep::edge_extent_sup(&arc, t0, t1);
            (
                arc,
                p.span,
                Margin::of(charge(extent.length(), slack)),
                SpanEnd::Stop,
            )
        }
        &(Piece::Segment { from, to, .. } | Piece::Ruling { from, to }) => {
            let length = geom_brep::ExtentBall::point(from).lever_from(to);
            let (chord, chord_length) = geom::Line::chord(from, to);
            (
                geom::Curve3::Line(chord),
                (T::zero(), chord_length),
                Margin::of(charge(length.length(), slack)),
                SpanEnd::Stop,
            )
        }
        Piece::Iso(p) => (
            p.carrier(),
            p.span,
            // No longer than its span at the curve's greatest speed: a
            // chord says nothing of the length of a curve that turns.
            Margin::metered_sup(p.span.1 - p.span.0, p.curve.speed_upper_bound()),
            if p.forward {
                SpanEnd::Stop
            } else {
                SpanEnd::Start
            },
        ),
    };
    // A piece of no length (a path's first, from an end already on the
    // turn's height, parallel or iso curve) crosses nothing: the next
    // piece starts at its point and reads a meeting there as its own
    // start (**`split_ring_path_spline_piece`**, its length).
    if decide("split_ring_path_spline_piece", extent, band)? == Sign::Zero {
        return Ok(Some(0));
    }
    let on_piece = Span::new(&curve, params);
    let on_arc = Span::new(carrier, *span);
    let met = match meet(&on_piece, &on_arc, band) {
        Ok(met) => met,
        Err(refusal) => return meet_refused(refusal.fault),
    };
    if met.shared.is_some() {
        return Ok(None);
    }
    let mut crossings = 0;
    for m in met.points {
        let (tp, ta) = match (m.on_a, m.on_b) {
            (Hit::End(end), Hit::On { .. }) if arrival && end == stop => continue,
            (Hit::On { t: tp, .. }, Hit::On { t: ta, .. }) => (tp, ta),
            _ => return Ok(None),
        };
        let (dp, da) = (curve.deriv(tp), carrier.deriv(ta));
        let sine = dp.cross(da).norm() / (dp.norm() * da.norm());
        // A crossing is a definite sign read at the meeting: its lever is
        // the piece's reach from there, from below (a piece met at its
        // middle reaches half its chord). No row holds the arc's: no pose
        // tried reaches this reading against a circle piece with a lever
        // that decides apart (`crossing_reach_rows`' module doc).
        let (t0, t1) = params;
        let length = crate::cover::piece_reach_bounds(
            &curve,
            params,
            (curve.eval(t0), curve.eval(t1)),
            curve.eval(tp),
        )
        .below();
        if decide(
            "split_ring_path_spline_across",
            Margin::levered(charge(sine, slack / length.length()), length),
            band,
        )? != Sign::Positive
        {
            return Ok(None);
        }
        crossings += 1;
    }
    Ok(Some(crossings))
}

/// **What a refused meeting of a piece and a spline arc says of the
/// path.** A meeting in band on the path is the path's, which says
/// nothing there, as a probe ray grazes; so does a limit of the reader
/// or a pose it has no closed form for. An escalation escalates. A
/// carrier of a kind its arm does not read, or two readings that
/// contradict, is the kernel's fault: a piece is a circle, a line or a
/// spline and the arc a spline, which the table reads, and a
/// contradiction is ruled out by the readings' definitions.
fn meet_refused(fault: geom_brep::curve_pair::MeetFault) -> Result<Option<usize>, Indeterminate> {
    use geom_brep::curve_pair::MeetKind;
    match fault.kind() {
        MeetKind::Escalated(diag) => Err(diag),
        MeetKind::Touch(_) | MeetKind::Unread(_) => Ok(None),
        MeetKind::Fault { what } => {
            unreachable!("the meeting of a path's piece and a spline arc faulted: {what}")
        }
    }
}

impl<T: Decide> ConicArc<T> {
    /// A lower bound on the distance from `x` to the arc: the distance
    /// to the arc of the circle of radius `b` over the same span
    /// ([`geom::Curve3::distance_within`], whose reading of a box is a
    /// floor under each of its points: `ring_path::arc_floor_rows`), less
    /// `|a − b|`, which bounds how far a conic point lies from the
    /// circle's at the same parameter.
    #[expect(
        clippy::disallowed_methods,
        reason = "a conic's centre frame, derived where an ellipse is held on its arc: owed a reading through the conic (work/oneround/one-stored-form-waits-on-the-readers-of-a-conics-centre.md)"
    )]
    pub(crate) fn distance_floor(&self, x: Point3<T>) -> T {
        let k = self.conic();
        let (f, (a, b)) = (k.frame(), k.semi_axes());
        let circle = geom::Curve3::Circle(geom::Circle::new(f, b));
        let Some(arc) = circle.distance_within(x, self.span) else {
            unreachable!("a circle's arc distance is closed-form")
        };
        arc - (a - b).abs()
    }
}

/// **Whether `t` lies inside `span`**, read at each end
/// (**`split_ring_path_in_span`**: the parameter's distance from the
/// end, metered at the rate `arm`, charged `slack` metres: `slack / arm`
/// in the parameter, [`charge`]), each reading kept whole, escalations
/// included.
///
/// **Its premise, which this door cannot check:** `t` and `span` are
/// both a parameter of `carrier`, the curve whose span is read: a piece's
/// own circle (`CircleArc::carrier`), a section arc's conic or oval, a
/// crest's circle, or a ruling's line, each handed by the arm that read
/// `t` off it. A ruling's carrier is formed from its line only to answer
/// that it has no period.
///
/// On a carrier with a period
/// ([`geom::Curve3::period`]) each end's distance is also read on `t`'s
/// copy a period away
/// ([`Period::span_margins`](geom_core::period::Period::span_margins)):
/// every periodic `t` read here is named about its span's middle
/// (`plane_roots`, `CircleArc::param`, `Conic::param_in`, `Oval::param`),
/// and a box across the middle's antipode is named whole on one copy, so
/// on a near-full arc its other copy can reach into the span past the
/// start (`span_turn_rows`). At `f64` the copy is no nearer. The period
/// is the carrier's answer, never one built here. The meter stays this
/// lane's own: a root's distance from an end is levered by the slope its
/// piece crosses the other's plane at ([`path_parity`]).
fn span_readings<T: Decide>(
    carrier: &geom::Curve3<T>,
    t: T,
    (lo, hi): (T, T),
    arm: T,
    slack: T,
    band: Band,
) -> [Result<Sign, Indeterminate>; 2] {
    let read = |m: T| {
        decide(
            "split_ring_path_in_span",
            Margin::metered(charge(m, slack / arm), InfSpeed::new(arm)),
            band,
        )
    };
    let (start, stop) = carrier
        .period()
        .map_or((t - lo, hi - t), |p| p.span_margins(t, (lo, hi)));
    [read(start), read(stop)]
}

/// **`m` shrunk toward zero by `slack`**, to zero inside it: a margin
/// charged with the rounding it may carry, so that its sign is decided
/// only past that rounding.
fn charge<T: Real>(m: T, slack: T) -> T {
    (m - slack).max(T::zero()) + (m + slack).min(T::zero())
}

/// **How far a reading's stored terms may part where they should
/// coincide, read about the reading's own point**: `4ε` times the
/// farthest of `points` from the first, `points[0]` the reading's own
/// point. A term stored far from the geometry a reading serves (a
/// cylinder's origin far along its axis, a section's centre far from its
/// arc) is summed with the reading's own coordinates, so the reading
/// rounds at that term's length: the stored form's amplification. The
/// coordinates' own rounding, about the world origin, is the run's
/// (`geom_core::tolerance::admissible`), and is not charged here. Each of
/// two points that should coincide is rounded at most twice, when it is
/// stored and in the one step that places it from stored points, so they
/// part by at most `2√3·ε·far` as a vector, which `4ε·far` bounds. A
/// reading charges this to its margin, so that where its stored terms
/// cannot resolve the band it stands down rather than decide on their
/// rounding.
fn resolution<T: Real>(points: &[Point3<T>]) -> T {
    let Some(&at) = points.first() else {
        return T::zero();
    };
    let far = points
        .iter()
        .fold(T::zero(), |m, &x| m.max((x - at).norm()));
    far * T::from_f64(4.0 * f64::EPSILON)
}

/// **The [`resolution`] of a reading between `path` and `arcs`**: of
/// every piece's ends and centre and every arc's stored centre, origin
/// or ends, read about the first of them (the first piece's first
/// stored term: an arc piece's centre, a segment's start); and a conic
/// arc's own
/// resolution over its span ([`geom_brep::carrier_resolution`]), the
/// rounding its stored semi-axes and far centre amplify.
#[expect(
    clippy::disallowed_methods,
    reason = "a circle's centre frame, which a circle stores: owed a reading through the conic (work/oneround/one-stored-form-waits-on-the-readers-of-a-conics-centre.md)"
)]
fn path_resolution<T: Decide>(path: &Path<T>, arcs: &[LoopArc<T>]) -> T {
    let mut points = Vec::with_capacity(3 * path.pieces.len() + arcs.len());
    for piece in &path.pieces {
        match piece {
            &(Piece::Arc(p) | Piece::Meridian(p)) => {
                points.extend([p.circle.frame().origin(), p.at(p.span.0), p.at(p.span.1)]);
            }
            &(Piece::Segment { from, to, .. } | Piece::Ruling { from, to }) => {
                points.extend([from, to]);
            }
            Piece::Iso(p) => {
                let (start, stop) = p.ends();
                points.extend([start, stop]);
            }
        }
    }
    for arc in arcs {
        match arc {
            LoopArc::Conic(_) => {}
            LoopArc::Crest { circle, .. } => points.push(circle.frame().origin()),
            LoopArc::Oval(Oval { frame, .. }) => points.push(frame.origin()),
            LoopArc::Line { line, .. } => points.push(line.origin),
            LoopArc::Spline(SplineArc { carrier, span }) => {
                points.extend([carrier.eval(span.0), carrier.eval(span.1)]);
            }
        }
    }
    let carriers = arcs.iter().filter_map(|arc| match arc {
        LoopArc::Conic(c) => {
            geom_brep::carrier_resolution::resolution(&c.carrier, c.span.0, c.span.1)
        }
        _ => None,
    });
    carriers.fold(resolution(&points), T::max)
}

/// **Whether the segment `from → to`, an end of which lies on
/// `conic`'s plane, misses the arc**
/// (**`split_ring_path_segment_apart`**): its midpoint is decided
/// farther from the arc ([`ConicArc::distance_floor`]) than half its
/// length, within which every point of it lies of the midpoint,
/// charged `slack` ([`charge`]).
fn segment_misses<T: Decide>(
    (from, to): (Point3<T>, Point3<T>),
    conic: &ConicArc<T>,
    slack: T,
    band: Band,
) -> Result<bool, Indeterminate> {
    let half = (to - from).norm() * T::from_f64(0.5);
    let mid = from.mid(to);
    Ok(decide(
        "split_ring_path_segment_apart",
        Margin::of(charge(conic.distance_floor(mid) - half, slack)),
        band,
    )? == Sign::Positive)
}

/// **Whether the circle piece `p`, which [`plane_roots`] cannot cut
/// with `conic`'s plane, misses the arc**: it runs along that plane,
/// as a path's meridian or parallel through a point of an arc's
/// carrier, or of its plane's other loop, does. Either:
/// - the two circles are decided apart
///   (**`split_ring_path_coplanar_apart`**: the annulus about the
///   conic's centre between `min(a, b)` and `max(a, b)`, which holds
///   the conic, against the piece's circle, by the centres' distance).
///   A point on both would bound that distance by the triangle
///   inequality, so the reading holds whatever the planes: a parallel
///   against its plane's other loop on a torus, a meridian against the
///   one across the axis; or
/// - they are one circle (**`split_ring_path_same_circle`**: the larger
///   of the centres' distance and each radius's difference; with
///   [`plane_roots`]' gap in the band, the planes then lie within the
///   band of each other too) and the arcs are decided disjoint on it:
///   each end of either lies outside the other's span
///   ([`span_readings`]). Two arcs of one circle overlap only where one
///   holds an end of the other.
///
/// `Ok(false)` where neither is decided. The apart and in-span readings
/// are charged `slack` ([`charge`]).
#[expect(
    clippy::disallowed_methods,
    reason = "a conic's centre frame, derived where an ellipse is held on its arc: owed a reading through the conic (work/oneround/one-stored-form-waits-on-the-readers-of-a-conics-centre.md)"
)]
fn misses_in_plane<T: Decide>(
    p: &CircleArc<T>,
    arc: &ConicArc<T>,
    slack: T,
    band: Band,
) -> Result<bool, Indeterminate> {
    if coplanar_apart(p, arc, slack, band)? {
        return Ok(true);
    }
    let conic = arc.conic();
    let (a, b) = conic.semi_axes();
    let apart = (p.circle.frame().origin() - conic.frame().origin()).norm();
    let differ = apart
        .max((p.circle.radius() - a).abs())
        .max((p.circle.radius() - b).abs());
    if decide("split_ring_path_same_circle", Margin::of(differ), band)? != Sign::Zero {
        return Ok(false);
    }
    // An end lies outside a span when either of its two readings is
    // decided outside; an escalation counts only where neither is.
    let outside =
        |carrier: &geom::Curve3<T>, t: T, span: (T, T), arm: T| -> Result<bool, Indeterminate> {
            let readings = span_readings(carrier, t, span, arm, slack, band);
            if readings.contains(&Ok(Sign::Negative)) {
                return Ok(true);
            }
            readings.iter().find_map(|r| r.err()).map_or(Ok(false), Err)
        };
    // Two overlapping arcs of one circle hold at least two ends inside
    // each other, so any three of the four readings decide the same.
    for t in [p.span.0, p.span.1] {
        if !outside(
            &arc.carrier,
            conic.param_in(p.at(t), arc.span),
            arc.span,
            conic.speed_lo(),
        )? {
            return Ok(false);
        }
    }
    for s in [arc.span.0, arc.span.1] {
        if !outside(
            &p.carrier(),
            p.param(conic.point_at(s)),
            p.span,
            p.circle.radius(),
        )? {
            return Ok(false);
        }
    }
    Ok(true)
}

/// **Whether the circle piece `p` and `arc`'s conic are decided apart**
/// (**`split_ring_path_coplanar_apart`**): the annulus about the conic's
/// centre between its least and greatest radius, which holds the conic,
/// against the piece's circle, by the centres' distance, charged `slack`
/// ([`charge`]). A point on both would bound that distance by the
/// triangle inequality, so the reading holds whatever the two planes:
/// [`misses_in_plane`]'s first arm, and [`path_parity`]'s answer past a
/// plane meeting [`plane_roots`] reads in band.
#[expect(
    clippy::disallowed_methods,
    reason = "a conic's centre frame, derived where an ellipse is held on its arc: owed a reading through the conic (work/oneround/one-stored-form-waits-on-the-readers-of-a-conics-centre.md)"
)]
fn coplanar_apart<T: Decide>(
    p: &CircleArc<T>,
    arc: &ConicArc<T>,
    slack: T,
    band: Band,
) -> Result<bool, Indeterminate> {
    let conic = arc.conic();
    let apart = (p.circle.frame().origin() - conic.frame().origin()).norm();
    let (inner, outer) = (conic.speed_lo(), conic.speed_hi());
    let gap = (apart - p.circle.radius() - outer)
        .max(inner - p.circle.radius() - apart)
        .max(p.circle.radius() - outer - apart);
    Ok(decide(
        "split_ring_path_coplanar_apart",
        Margin::of(charge(gap, slack)),
        band,
    )? == Sign::Positive)
}

/// **Where the circle piece `p` meets the plane of `plane`, with unit
/// normal `n`**, the plane its loop arc lies in (the piece is read across
/// the arc's plane, which is transversal to the surface all along the
/// arc; a crest's, which touches it, is read across the cylinder instead): the crossing reading's meetings
/// ([`geom_brep::curve_face::cross()`]) on the piece's span, each with
/// the slope `|n̂·τ̂|` the piece crosses the plane at. A meeting inside
/// the span is its parameter and reads inside the piece; one at an end
/// reads on the piece's end (`InSpan::End`). `Lies`, `Tangent` and
/// windows all read in the zero band are [`PlaneMeet::Along`]: the piece
/// runs along the plane or grazes it. A window read in its escalation gap
/// escalates; one a limit left unread is [`PlaneMeet::Unread`]; a fault
/// fails loud ([`refused`]). On the arrival arc (`arrival`), the meeting nearest the
/// piece's end is the arrival and only the others are read: the last, as
/// the reading orders them, with no decision of its own.
fn plane_roots<T: Decide>(
    p: &CircleArc<T>,
    plane: &geom::Frame<T>,
    arrival: bool,
    band: Band,
) -> Result<PlaneMeet<T>, Indeterminate> {
    use geom_brep::curve_face::{OnSpan, Pose};
    let carrier = p.carrier();
    let span = geom_brep::curve_pair::Span::new(&carrier, p.span);
    let n = plane.axis();
    let plane = geom::Surface::Plane { frame: *plane };
    let meetings = match geom_brep::curve_face::cross(&span, &plane, band) {
        Ok(read) => match read.pose {
            Pose::Apart | Pose::Isolated(_) => read.meetings,
            Pose::Lies | Pose::Tangent(_) | Pose::Through(_) => return Ok(PlaneMeet::Along),
        },
        Err(refusal) => {
            // The windows' worst reading: an escalation asks the next path
            // before an unread stretch says nothing, and only windows all
            // read in the zero band keep the piece along the plane.
            let mut worst = Refused::Along;
            for w in &refusal.windows {
                match refused(w.why) {
                    Refused::Escalated(diag) => return Err(diag),
                    Refused::Unread => worst = Refused::Unread,
                    Refused::Along => {}
                }
            }
            return Ok(match worst {
                Refused::Unread => PlaneMeet::Unread,
                Refused::Along | Refused::Escalated(_) => PlaneMeet::Along,
            });
        }
    };
    let mut at: Vec<InSpan<T>> = meetings
        .iter()
        .map(|m| match m.on_span {
            OnSpan::Inside { t } => InSpan::Inside(t),
            OnSpan::End(geom_brep::curve_pair::SpanEnd::Start) => InSpan::End(p.span.0),
            OnSpan::End(geom_brep::curve_pair::SpanEnd::Stop) => InSpan::End(p.span.1),
        })
        .collect();
    // The meetings ascend along the span, so the last is the nearer the
    // piece's end.
    if arrival {
        at.pop();
    }
    // A carrier moved by δ moves the root by δ over the slope the piece
    // crosses the plane at, `|n̂·τ̂|`: each in-span reading of the other
    // arc is levered by it.
    let (ca, cb) = (n.dot(p.circle.u_ref()), n.dot(p.circle.v_ref()));
    Ok(PlaneMeet::Meets(
        at.into_iter()
            .map(|m| {
                let (st, ct) = m.t().sin_cos();
                (m, (cb * ct - ca * st).abs())
            })
            .collect(),
    ))
}

/// A meeting [`plane_roots`] read, with the slope the piece crosses at.
type PieceMeeting<T> = (InSpan<T>, T);

/// **What [`plane_roots`] read of the piece against the plane.**
#[derive(Debug)]
enum PlaneMeet<T> {
    /// Its meetings, each with its slope.
    Meets(Vec<PieceMeeting<T>>),
    /// It runs along the plane or grazes it, read in the zero band: the
    /// premise [`misses_in_plane`] reads the pair under.
    Along,
    /// A stretch of it was not read, and no margin says how far it was:
    /// the path says nothing here, and another may.
    Unread,
}

/// **One unread window of the crossing reading, as the ring path takes
/// it** ([`refused`]).
#[derive(Debug)]
enum Refused {
    /// Read in its escalation gap: the caller asks the next path.
    Escalated(Indeterminate),
    /// Read in the zero band: a graze or a run along the plane.
    Along,
    /// A limit of the reading: a meter or a root finder that could not
    /// settle, or a pose with no closed form.
    Unread,
}

/// **What an unread window of a circle piece's crossing reading against
/// a plane says to the path**, by what the refusal means.
///
/// # Panics
///
/// On a kernel fault (readings that contradict, a carrier an arm misread)
/// and on a refusal a circle against a plane cannot raise (a torus
/// outside the convention, an unbuilt or enclosed arm, a spline's piece
/// walk): each is a fault of the reading, never a pose.
fn refused(why: geom_brep::curve_face::CrossWhy) -> Refused {
    use geom_brep::curve_face::{CrossWhy, PoseRefusal};
    use geom_brep::curve_pair::MeetFault;
    use geom_brep::roots::Unsettled;
    let zero_or = |diag: Indeterminate| match diag.margin.rejected_sign() {
        Some(Sign::Zero) => Refused::Along,
        _ => Refused::Escalated(diag),
    };
    match why {
        CrossWhy::Pose(PoseRefusal::InBand { diag, .. }) => zero_or(diag),
        CrossWhy::Pose(PoseRefusal::Meter { .. }) => Refused::Unread,
        CrossWhy::Pose(PoseRefusal::Fault(what)) => {
            unreachable!("a ring path's plane crossing is a kernel fault: {what}")
        }
        CrossWhy::Pose(
            refusal @ (PoseRefusal::Enclosed | PoseRefusal::Unbuilt(_) | PoseRefusal::Torus(_)),
        ) => unreachable!("a circle against a plane raised {refusal:?}, a kernel fault"),
        CrossWhy::Method { fault, .. } => match fault {
            MeetFault::Escalated(diag) | MeetFault::Touch(diag) => Refused::Escalated(diag),
            // A touch or a run read in the zero band.
            MeetFault::Unsettled(Unsettled::Tangency | Unsettled::Degenerate) => Refused::Along,
            MeetFault::Unsettled(
                Unsettled::Meter { .. }
                | Unsettled::Exhausted
                | Unsettled::Floor
                | Unsettled::Resolvent
                | Unsettled::CountDisagrees { .. }
                | Unsettled::AtApex
                | Unsettled::Crease
                | Unsettled::Reach,
            )
            | MeetFault::Unsupported { .. } => Refused::Unread,
            MeetFault::Desync | MeetFault::Contradiction { .. } | MeetFault::Unwalked(_) => {
                unreachable!("a ring path's plane crossing is a kernel fault: {fault:?}")
            }
        },
    }
}

/// **Where a meeting [`plane_roots`] read sits on the piece**: inside its
/// span, at its parameter, or on an end, at the end's parameter.
#[derive(Clone, Copy, Debug)]
enum InSpan<T> {
    Inside(T),
    End(T),
}

impl<T: Copy> InSpan<T> {
    fn t(self) -> T {
        match self {
            Self::Inside(t) | Self::End(t) => t,
        }
    }

    /// The piece's own in-span readings: inside is past both ends, an end
    /// on one.
    fn readings(self) -> [Result<Sign, Indeterminate>; 2] {
        match self {
            Self::Inside(_) => [Ok(Sign::Positive), Ok(Sign::Positive)],
            Self::End(_) => [Ok(Sign::Zero), Ok(Sign::Zero)],
        }
    }
}

