    /// **A piece that runs along the cylinder `ρ = R` says nothing of a
    /// crest arc**: a parallel of radius `R` over the arc's span
    /// (**`split_ring_path_crest_graze`**), a segment from the arc up a
    /// tube radius, and a segment whose ends lie either side of the
    /// cylinder (**`split_ring_path_crest_side`**), each read against the
    /// tube's top arc of the island "up to the top" alone, in three
    /// frames. [`Quadric::paths`] builds none of these where it would
    /// decide a parity: the meridian or the lead its parallel at `R`
    /// follows ends on the crest circle and is read undecided first
    /// (`a_path_from_the_tubes_top_or_bottom_reads_the_oracle_or_nothing`
    /// stays green with either guard dropped), so this row holds the
    /// guards to their contract. Red against the mutants "graze verdict
    /// ignored" and "lead-side check removed".
    #[test]
    fn a_piece_along_the_crest_cylinder_says_nothing_of_a_crest_arc() {
        use super::torus_islands::{RADII, crest_islands, on_torus, torus};
        use core::f64::consts::FRAC_PI_2;
        for f in frames() {
            let quadric = Quadric::of(&torus(f, false)).unwrap();
            let (_, island) = crest_islands(f).into_iter().next().unwrap();
            let crest: Vec<_> = torus_arcs(&quadric, &island)
                .into_iter()
                .filter(|arc| matches!(arc, LoopArc::Crest { .. }))
                .collect();
            assert_eq!(crest.len(), 1, "the island's one crest arc");
            let round = CircleArc {
                circle: geom::Circle::new(
                    geom::Frame::new(f.at(0.0, 0.0, RADII.1), f.z, f.x),
                    RADII.0 * f.s,
                ),
                span: (-1.0, 1.0),
            };
            let top = on_torus(f, 0.0, FRAC_PI_2);
            let segment = |from: Point3<f64>, to: Point3<f64>| Piece::Segment {
                from,
                to,
                ruling: Vec3::zero(),
                lever: geom_brep::ExtentBall::point(from).lever(),
            };
            for (what, piece) in [
                ("a parallel along the crest", Piece::Arc(round)),
                (
                    "a segment up from the crest",
                    segment(top, top + f.z * 0.1 * f.s),
                ),
                (
                    "a segment across the cylinder",
                    segment(on_torus(f, 0.0, 1.2), on_torus(f, 0.0, 2.0)),
                ),
            ] {
                let path = Path {
                    pieces: vec![piece],
                    arrival: f.z,
                    reach: None,
                };
                assert_eq!(
                    path_parity(&path, &crest, None, band()).unwrap(),
                    None,
                    "{what}: decided"
                );
            }
        }
    }

    /// **A circle piece decided apart from a conic arc misses it, past a
    /// plane meeting read in band** ([`coplanar_apart`]): the piece, a
    /// unit circle in the `xz` plane, rises to the conic's plane `z = h`
    /// within the band of touching it (its gap `1 − h` mid-band), so
    /// [`plane_roots`] refuses; the conic, a unit circle about
    /// `(10, 0, h)`, lies decided apart from it whatever the planes. The
    /// pair crosses nowhere and flips nothing. Red against the old order,
    /// which refused at the plane meeting.
    #[test]
    fn a_circle_apart_from_a_conic_misses_it_past_a_plane_meeting_in_band() {
        let gray = 0.5 * (band().zero() + band().escalate());
        let h = 1.0 - gray;
        let o = Point3::new(0.0, 0.0, 0.0);
        let (x, y, z) = (
            Vec3::new(1.0, 0.0, 0.0),
            Vec3::new(0.0, 1.0, 0.0),
            Vec3::new(0.0, 0.0, 1.0),
        );
        let piece = CircleArc {
            circle: geom::Circle::new(geom::Frame::new(o, y, x), 1.0),
            span: (-1.0, 1.0),
        };
        let arc = LoopArc::of(
            &geom::Curve3::circle(Point3::new(10.0, 0.0, h), z, 1.0, x),
            (0.0, 1.0),
        )
        .expect("a circle is a conic arc");
        let sec = arc.plane().expect("a conic's plane");
        assert!(
            plane_roots(&piece, &sec.plane, false, band()).is_err(),
            "the plane meeting is in band"
        );
        let path = Path {
            pieces: vec![Piece::Arc(piece)],
            arrival: z,
            reach: None,
        };
        assert_eq!(
            path_parity(&path, core::slice::from_ref(&arc), None, band()),
            Ok(Some(false)),
            "decided apart: no crossing"
        );
    }

    /// **A segment with one end decided on the crest cylinder says nothing
